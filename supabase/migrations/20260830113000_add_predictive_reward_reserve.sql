create table public.reward_budget_epochs (
  id bigint generated by default as identity primary key,
  network text not null
    check (network in ('mainnet','testnet','testnet-staging')),
  app_id text not null
    check (app_id ~ '^0x[0-9a-f]{64}$'),
  allocation_receipt_id bigint not null
    references public.vebetter_round_allocations(id),
  vebetter_round_id bigint not null
    check (vebetter_round_id >= 1),
  allocation_rewards_wei numeric(78,0) not null
    check (allocation_rewards_wei >= 0 and allocation_rewards_wei = trunc(allocation_rewards_wei)),
  opening_pool_balance_wei numeric(78,0) not null
    check (opening_pool_balance_wei >= 0 and opening_pool_balance_wei = trunc(opening_pool_balance_wei)),
  opening_reserved_wei numeric(78,0) not null
    check (opening_reserved_wei >= 0 and opening_reserved_wei = trunc(opening_reserved_wei)),
  expected_completions integer not null
    check (expected_completions >= 0),
  stress_completions integer not null
    check (stress_completions >= 1),
  reward_per_invite_wei numeric(78,0) not null
    check (reward_per_invite_wei >= 0 and reward_per_invite_wei = trunc(reward_per_invite_wei)),
  algorithm_version text not null
    check (length(btrim(algorithm_version)) between 1 and 80),
  pipeline_snapshot jsonb not null
    check (jsonb_typeof(pipeline_snapshot) = 'object'),
  created_at timestamptz not null default now(),
  constraint reward_budget_epochs_allocation_uidx
    unique (allocation_receipt_id),
  constraint reward_budget_epochs_round_uidx
    unique (network, app_id, vebetter_round_id)
);

