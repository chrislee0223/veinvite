create or replace function public.read_predictive_reward_planning_snapshot(
  p_network text,
  p_app_id text
)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_veinvite_app_id constant text :=
    '0x29acc8863cf2ab7a82d16c62d61ca84b6650cede4c4fd69073148c875349021e';
  v_latest public.vebetter_round_allocations%rowtype;
  v_epoch public.reward_budget_epochs%rowtype;
  v_reserved numeric(78,0) := 0;
  v_queued integer := 0;
  v_vote_ready integer := 0;
  v_vot3_ready integer := 0;
  v_apps_two integer := 0;
  v_apps_one integer := 0;
  v_activated_zero integer := 0;
  v_pending_acceptance integer := 0;
begin
  p_network := lower(btrim(p_network));
  p_app_id := lower(btrim(p_app_id));

  if p_network not in ('mainnet','testnet','testnet-staging') then
    raise exception 'unsupported network';
  end if;

  if p_app_id <> v_veinvite_app_id then
    raise exception 'predictive reward planning only supports the VeInvite app';
  end if;

  select coalesce(sum(rp.amount_wei), 0)
  into v_reserved
  from public.reward_payouts rp
  join public.reward_rounds rr on rr.id = rp.round_id
  where rr.network = p_network
    and rr.app_id = p_app_id
    and rp.status in ('PENDING','SENDING','FAILED');

  select count(*)
  into v_queued
  from public.reward_queue_entries q
  where q.network = p_network
    and q.status = 'QUEUED'
    and q.assigned_round_id is null;

  select count(*)
  into v_vote_ready
  from public.invitations i
  where i.activation_network = p_network
    and i.status = 'ACTIVATING'
    and i.reward_eligible_at is null
    and i.activated_at is not null
    and i.apps_completed >= 3
    and coalesce(i.vot3_converted, false) = true
    and coalesce(i.vote_completed, false) = false;

  select count(*)
  into v_vot3_ready
  from public.invitations i
  where i.activation_network = p_network
    and i.status = 'ACTIVATING'
    and i.reward_eligible_at is null
    and i.activated_at is not null
    and i.apps_completed >= 3
    and coalesce(i.vot3_converted, false) = false;

  select count(*)
  into v_apps_two
  from public.invitations i
  where i.activation_network = p_network
    and i.status = 'ACTIVATING'
    and i.reward_eligible_at is null
    and i.activated_at is not null
    and i.apps_completed = 2;

  select count(*)
  into v_apps_one
  from public.invitations i
  where i.activation_network = p_network
    and i.status = 'ACTIVATING'
    and i.reward_eligible_at is null
    and i.activated_at is not null
    and i.apps_completed = 1;

  select count(*)
  into v_activated_zero
  from public.invitations i
  where i.activation_network = p_network
    and i.status = 'ACTIVATING'
    and i.reward_eligible_at is null
    and i.activated_at is not null
    and i.apps_completed <= 0;

  select count(*)
  into v_pending_acceptance
  from public.invitations i
  where i.status = 'PENDING_ACCEPTANCE'
    and i.reward_eligible_at is null;

  select *
  into v_latest
  from public.vebetter_round_allocations a
  where a.network = p_network
    and a.app_id = p_app_id
  order by a.vebetter_round_id desc
  limit 1;

  if found then
    select *
    into v_epoch
    from public.reward_budget_epochs e
    where e.allocation_receipt_id = v_latest.id;
  end if;

  return jsonb_build_object(
    'reservedExistingWei', v_reserved::text,
    'pipeline', jsonb_build_object(
      'queuedEligibleCount', v_queued,
      'voteReadyCount', v_vote_ready,
      'vot3ReadyCount', v_vot3_ready,
      'appsTwoCount', v_apps_two,
      'appsOneCount', v_apps_one,
      'activatedZeroCount', v_activated_zero,
      'pendingAcceptanceCount', v_pending_acceptance
    ),
    'latestAllocation', case
      when v_latest.id is null then null
      else jsonb_build_object(
        'id', v_latest.id,
        'veBetterRoundId', v_latest.vebetter_round_id,
        'rewardsAllocationWei', v_latest.rewards_allocation_amount_wei::text,
        'claimBlockTimestamp', v_latest.claim_block_timestamp
      )
    end,
    'activeEpoch', case
      when v_epoch.id is null then null
      else jsonb_build_object(
        'id', v_epoch.id,
        'veBetterRoundId', v_epoch.vebetter_round_id,
        'allocationRewardsWei', v_epoch.allocation_rewards_wei::text,
        'openingPoolBalanceWei', v_epoch.opening_pool_balance_wei::text,
        'openingReservedWei', v_epoch.opening_reserved_wei::text,
        'expectedCompletions', v_epoch.expected_completions,
        'stressCompletions', v_epoch.stress_completions,
        'rewardPerInviteWei', v_epoch.reward_per_invite_wei::text,
        'algorithmVersion', v_epoch.algorithm_version,
        'pipelineSnapshot', v_epoch.pipeline_snapshot,
        'createdAt', v_epoch.created_at
      )
    end
  );
end;
$$;

revoke all on function public.read_predictive_reward_planning_snapshot(text, text)
  from public, anon, authenticated;
grant execute on function public.read_predictive_reward_planning_snapshot(text, text)
  to service_role;

create or replace function public.prepare_predictive_reward_batch(
  p_network text,
  p_app_id text,
  p_pool_balance_wei numeric,
  p_allocation_receipt_id bigint,
  p_expected_completions integer,
  p_stress_completions integer,
  p_reward_per_invite_wei numeric,
  p_algorithm_version text,
  p_pipeline_snapshot jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_veinvite_app_id constant text :=
    '0x29acc8863cf2ab7a82d16c62d61ca84b6650cede4c4fd69073148c875349021e';
  v_receipt public.vebetter_round_allocations%rowtype;
  v_epoch public.reward_budget_epochs%rowtype;
  v_reserved_existing numeric(78,0) := 0;
  v_available numeric(78,0) := 0;
  v_expected_reward numeric(78,0) := 0;
  v_capacity bigint := 0;
  v_candidate_codes text[] := array[]::text[];
  v_eligible_count integer := 0;
  v_round_id bigint;
  v_distributable numeric(78,0) := 0;
  v_remainder numeric(78,0) := 0;
  v_payout_count integer := 0;
  v_assigned_count integer := 0;
  v_now timestamptz := now();
begin
  p_network := lower(btrim(p_network));
  p_app_id := lower(btrim(p_app_id));
  p_algorithm_version := btrim(p_algorithm_version);

  if p_network not in ('mainnet','testnet','testnet-staging') then
    raise exception 'unsupported network';
  end if;

  if p_app_id <> v_veinvite_app_id then
    raise exception 'predictive rewards can only target the VeInvite app';
  end if;

  if p_pool_balance_wei is null
     or p_pool_balance_wei < 0
     or p_pool_balance_wei <> trunc(p_pool_balance_wei) then
    raise exception 'pool balance must be a non-negative integer';
  end if;

  if p_expected_completions is null or p_expected_completions < 0 then
    raise exception 'expected completions must be non-negative';
  end if;

  if p_stress_completions is null
     or p_stress_completions < 4
     or p_stress_completions < p_expected_completions then
    raise exception 'stress completions are below the predictive safety floor';
  end if;

  if p_reward_per_invite_wei is null
     or p_reward_per_invite_wei < 0
     or p_reward_per_invite_wei <> trunc(p_reward_per_invite_wei) then
    raise exception 'reward per invite must be a non-negative integer';
  end if;

  if p_algorithm_version is null or length(p_algorithm_version) not between 1 and 80 then
    raise exception 'predictive reward algorithm version is invalid';
  end if;

  if p_pipeline_snapshot is null or jsonb_typeof(p_pipeline_snapshot) <> 'object' then
    raise exception 'pipeline snapshot must be a JSON object';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended(
      'veinvite_predictive_reward_' || p_network || '_' || p_app_id,
      0
    )
  );

  if exists (
    select 1
    from public.reward_rounds rr
    where rr.network = p_network
      and rr.app_id = p_app_id
      and rr.status in ('CREATED','PAYING')
  ) then
    raise exception 'Finish the current reward round before preparing another one';
  end if;

  select *
  into v_receipt
  from public.vebetter_round_allocations a
  where a.id = p_allocation_receipt_id
  for share;

  if not found then
    raise exception 'VeBetter allocation receipt not found';
  end if;

  if v_receipt.network <> p_network or v_receipt.app_id <> p_app_id then
    raise exception 'VeBetter allocation receipt does not match the active reward pool';
  end if;

  if exists (
    select 1
    from public.vebetter_round_allocations newer
    where newer.network = p_network
      and newer.app_id = p_app_id
      and newer.vebetter_round_id > v_receipt.vebetter_round_id
  ) then
    raise exception 'VeBetter allocation receipt is not the latest observed funding round';
  end if;

  if v_receipt.rewards_allocation_amount_wei <= 0 then
    return jsonb_build_object(
      'epochId', null,
      'roundId', null,
      'epochCreated', false,
      'reason', 'NO_FUNDED_ALLOCATION'
    );
  end if;

  select coalesce(sum(rp.amount_wei), 0)
  into v_reserved_existing
  from public.reward_payouts rp
  join public.reward_rounds rr on rr.id = rp.round_id
  where rr.network = p_network
    and rr.app_id = p_app_id
    and rp.status in ('PENDING','SENDING','FAILED');

  v_available := greatest(p_pool_balance_wei - v_reserved_existing, 0);

  select *
  into v_epoch
  from public.reward_budget_epochs e
  where e.allocation_receipt_id = v_receipt.id;

  if not found then
    v_expected_reward := floor(
      least(v_receipt.rewards_allocation_amount_wei, v_available)
      / p_stress_completions
    );

    if v_expected_reward <> p_reward_per_invite_wei then
      raise exception 'predictive reward amount does not match the reviewed allocation, reserve and stress denominator';
    end if;

    insert into public.reward_budget_epochs(
      network,
      app_id,
      allocation_receipt_id,
      vebetter_round_id,
      allocation_rewards_wei,
      opening_pool_balance_wei,
      opening_reserved_wei,
      expected_completions,
      stress_completions,
      reward_per_invite_wei,
      algorithm_version,
      pipeline_snapshot
    ) values (
      p_network,
      p_app_id,
      v_receipt.id,
      v_receipt.vebetter_round_id,
      v_receipt.rewards_allocation_amount_wei,
      p_pool_balance_wei,
      v_reserved_existing,
      p_expected_completions,
      p_stress_completions,
      p_reward_per_invite_wei,
      p_algorithm_version,
      p_pipeline_snapshot
    )
    returning * into v_epoch;
  end if;

  if v_epoch.reward_per_invite_wei <= 0 or v_available <= 0 then
    return jsonb_build_object(
      'epochId', v_epoch.id,
      'roundId', null,
      'epochCreated', v_epoch.created_at = v_now,
      'reason', 'NO_AVAILABLE_REWARD_CAPACITY',
      'rewardPerInviteWei', v_epoch.reward_per_invite_wei::text,
      'availableWei', v_available::text
    );
  end if;

  v_capacity := floor(v_available / v_epoch.reward_per_invite_wei);

  if v_capacity < 1 then
    return jsonb_build_object(
      'epochId', v_epoch.id,
      'roundId', null,
      'epochCreated', false,
      'reason', 'NO_AVAILABLE_REWARD_CAPACITY',
      'rewardPerInviteWei', v_epoch.reward_per_invite_wei::text,
      'availableWei', v_available::text
    );
  end if;

  select coalesce(
    array_agg(c.invite_code order by c.eligible_at, c.invite_code),
    array[]::text[]
  )
  into v_candidate_codes
  from (
    select q.invite_code, q.eligible_at
    from public.reward_queue_entries q
    join public.invitations i
      on i.invite_code = q.invite_code
    join public.eligibility_check_events e
      on e.id = q.eligibility_check_id
     and e.id = i.eligibility_check_id
     and e.invite_code = i.invite_code
    where q.network = p_network
      and q.status = 'QUEUED'
      and q.assigned_round_id is null
      and i.status = 'COMPLETED'
      and i.reward_status = 'ELIGIBLE'
      and i.reward_eligible_at is not null
      and q.eligible_at = i.reward_eligible_at
      and i.sybil_status = 'CLEAR'
      and i.sybil_checked_at is not null
      and i.activation_network = p_network
      and i.activation_block is not null
      and i.invitee_wallet is not null
      and i.inviter_wallet is not null
      and q.recipient_wallet = lower(i.inviter_wallet)
      and e.wallet_address = lower(i.invitee_wallet)
      and e.network = p_network
      and e.outcome = 'ELIGIBLE'
      and e.entry_class in ('NEW','RETURNING')
      and e.entry_class = q.entry_class
      and e.checked_block <= i.activation_block
      and i.impact_sync_complete_at is not null
      and i.apps_completed >= 3
      and i.apps_completed_at is not null
      and i.apps_completed_block is not null
      and i.vot3_converted = true
      and i.vot3_converted_at is not null
      and i.vot3_converted_block is not null
      and i.vot3_conversion_tx_id is not null
      and i.vot3_conversion_amount_wei is not null
      and i.vote_completed = true
      and i.vote_completed_at is not null
      and i.vote_completed_block is not null
      and i.vote_round_id is not null
      and i.sybil_checked_at >= i.vote_completed_at
      and (
        select count(distinct d.app_id)
        from public.invite_impact_events d
        where d.invite_code = i.invite_code
          and d.network = p_network
          and d.wallet_address = lower(i.invitee_wallet)
          and d.event_type = 'DAPP_REWARD'
          and d.block_number >= i.activation_block
          and d.block_number <= i.apps_completed_block
      ) >= 3
      and exists (
        select 1
        from public.invite_impact_events c
        where c.invite_code = i.invite_code
          and c.network = p_network
          and c.wallet_address = lower(i.invitee_wallet)
          and c.event_type = 'VOT3_CONVERSION'
          and c.tx_id = i.vot3_conversion_tx_id
          and c.block_number = i.vot3_converted_block
          and c.block_timestamp = i.vot3_converted_at
          and c.amount_wei = i.vot3_conversion_amount_wei
          and c.amount_wei ~ '^[0-9]+$'
          and c.amount_wei::numeric >= 1000000000000000000
          and c.tx_index is not null
          and c.clause_index is not null
          and exists (
            select 1
            from public.invite_impact_events d
            where d.invite_code = i.invite_code
              and d.network = p_network
              and d.wallet_address = lower(i.invitee_wallet)
              and d.event_type = 'DAPP_REWARD'
              and d.block_number >= i.activation_block
              and d.tx_index is not null
              and d.clause_index is not null
              and (
                d.block_number < c.block_number
                or (
                  d.block_number = c.block_number
                  and (
                    d.tx_index < c.tx_index
                    or (
                      d.tx_index = c.tx_index
                      and d.clause_index < c.clause_index
                    )
                  )
                )
              )
          )
          and exists (
            select 1
            from public.invite_impact_events v
            where v.invite_code = i.invite_code
              and v.network = p_network
              and v.wallet_address = lower(i.invitee_wallet)
              and v.event_type = 'ALLOCATION_VOTE'
              and v.block_number = i.vote_completed_block
              and v.block_timestamp = i.vote_completed_at
              and v.vote_round_id = i.vote_round_id
              and v.tx_index is not null
              and v.clause_index is not null
              and (
                c.block_number < v.block_number
                or (
                  c.block_number = v.block_number
                  and (
                    c.tx_index < v.tx_index
                    or (
                      c.tx_index = v.tx_index
                      and c.clause_index < v.clause_index
                    )
                  )
                )
              )
          )
      )
      and not exists (
        select 1
        from public.reward_payouts rp
        where rp.invite_code = q.invite_code
      )
    order by q.eligible_at, q.invite_code
    limit v_capacity
    for update of q, i
  ) c;

  v_eligible_count := coalesce(cardinality(v_candidate_codes), 0);

  if v_eligible_count = 0 then
    return jsonb_build_object(
      'epochId', v_epoch.id,
      'roundId', null,
      'epochCreated', false,
      'reason', 'NO_SETTLEABLE_CANDIDATES',
      'rewardPerInviteWei', v_epoch.reward_per_invite_wei::text,
      'availableWei', v_available::text
    );
  end if;

  v_distributable := v_epoch.reward_per_invite_wei * v_eligible_count;
  v_remainder := v_available - v_distributable;

  insert into public.reward_rounds(
    network,
    app_id,
    status,
    observed_pool_balance_wei,
    reserved_before_round_wei,
    distributable_wei,
    eligible_count,
    per_reward_wei,
    remainder_wei,
    reward_budget_epoch_id
  ) values (
    p_network,
    p_app_id,
    'CREATED',
    p_pool_balance_wei,
    v_reserved_existing,
    v_distributable,
    v_eligible_count,
    v_epoch.reward_per_invite_wei,
    v_remainder,
    v_epoch.id
  )
  returning id into v_round_id;

  insert into public.reward_payouts(
    round_id,
    invite_code,
    recipient_wallet,
    amount_wei,
    status
  )
  select
    v_round_id,
    q.invite_code,
    q.recipient_wallet,
    v_epoch.reward_per_invite_wei,
    'PENDING'
  from public.reward_queue_entries q
  where q.invite_code = any(v_candidate_codes)
    and q.status = 'QUEUED'
    and q.assigned_round_id is null
  order by q.eligible_at, q.invite_code;

  get diagnostics v_payout_count = row_count;

  if v_payout_count <> v_eligible_count then
    raise exception
      'reward payout reservation count % does not match candidate count %',
      v_payout_count,
      v_eligible_count;
  end if;

  update public.reward_queue_entries q
  set
    status = 'ASSIGNED',
    assigned_round_id = v_round_id,
    assigned_at = v_now
  where q.invite_code = any(v_candidate_codes)
    and q.status = 'QUEUED'
    and q.assigned_round_id is null;

  get diagnostics v_assigned_count = row_count;

  if v_assigned_count <> v_eligible_count then
    raise exception
      'reward queue assignment count % does not match candidate count %',
      v_assigned_count,
      v_eligible_count;
  end if;

  return jsonb_build_object(
    'epochId', v_epoch.id,
    'roundId', v_round_id,
    'epochCreated', false,
    'reason', 'BATCH_PREPARED',
    'rewardPerInviteWei', v_epoch.reward_per_invite_wei::text,
    'recipientCount', v_eligible_count,
    'distributableWei', v_distributable::text,
    'remainingReserveWei', v_remainder::text
  );
end;
$$;

