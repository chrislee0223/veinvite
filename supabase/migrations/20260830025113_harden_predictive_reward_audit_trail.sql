create or replace function public.create_reward_receipt_from_paid_payout()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_round public.reward_rounds%rowtype;
  v_epoch public.reward_budget_epochs%rowtype;
  v_settlement public.reward_payout_transaction_settlements%rowtype;
  v_existing public.reward_receipts%rowtype;
  v_vebetter_round_id bigint;
begin
  if new.status <> 'PAID'
     or old.status = 'PAID' then
    return new;
  end if;

  if new.tx_id is null or new.paid_at is null then
    raise exception 'PAID payout is missing transaction evidence';
  end if;

  if not exists (
    select 1
    from public.invitations i
    where i.invite_code = new.invite_code
      and i.inviter_wallet = new.recipient_wallet
  ) then
    raise exception 'reward receipt recipient must be the invitation inviter';
  end if;

  select * into v_round
  from public.reward_rounds
  where id = new.round_id;

  if not found then
    raise exception 'reward receipt reward round was not found';
  end if;

  if v_round.reward_budget_epoch_id is not null then
    select * into v_epoch
    from public.reward_budget_epochs e
    where e.id = v_round.reward_budget_epoch_id;

    if not found then
      raise exception 'reward receipt predictive budget epoch was not found';
    end if;

    if v_epoch.network <> v_round.network
       or v_epoch.app_id <> v_round.app_id then
      raise exception 'reward receipt predictive budget epoch does not match reward round';
    end if;

    v_vebetter_round_id := v_epoch.vebetter_round_id;
  elsif v_round.vebetter_round_id is not null
        and v_round.allocation_receipt_id is not null
        and v_round.allocation_rewards_wei is not null
        and v_round.opening_carryover_wei is not null then
    v_vebetter_round_id := v_round.vebetter_round_id;
  else
    raise exception 'reward receipt requires an allocation or predictive-budget bound reward round';
  end if;

  select * into v_settlement
  from public.reward_payout_transaction_settlements s
  where s.round_id = new.round_id
    and s.tx_id = new.tx_id;

  if not found then
    raise exception 'reward receipt requires a finalized payout settlement';
  end if;

  if v_settlement.network <> v_round.network
     or v_settlement.paid_at <> new.paid_at
     or v_settlement.finalized_head_number < v_settlement.block_number then
    raise exception 'reward receipt settlement evidence does not match the paid payout';
  end if;

  insert into public.reward_receipts(
    payout_id, round_id, settlement_id, network, vebetter_round_id,
    invite_code, recipient_wallet, amount_wei, tx_id, paid_at
  ) values (
    new.id, new.round_id, v_settlement.id, v_round.network,
    v_vebetter_round_id, new.invite_code, new.recipient_wallet,
    new.amount_wei, new.tx_id, new.paid_at
  )
  on conflict (payout_id) do nothing;

  if not found then
    select * into v_existing
    from public.reward_receipts
    where payout_id = new.id;

    if not found
       or v_existing.round_id <> new.round_id
       or v_existing.settlement_id <> v_settlement.id
       or v_existing.network <> v_round.network
       or v_existing.vebetter_round_id <> v_vebetter_round_id
       or v_existing.invite_code <> new.invite_code
       or v_existing.recipient_wallet <> new.recipient_wallet
       or v_existing.amount_wei <> new.amount_wei
       or v_existing.tx_id <> new.tx_id
       or v_existing.paid_at <> new.paid_at then
      raise exception 'existing reward receipt does not match immutable payout evidence';
    end if;
  end if;

  return new;
end;
$$;

create or replace view public.operator_vebetter_round_accounting
with (security_invoker = true)
as
with round_bindings as (
  select
    rr.*,
    coalesce(rr.allocation_receipt_id, e.allocation_receipt_id) as effective_allocation_receipt_id
  from public.reward_rounds rr
  left join public.reward_budget_epochs e
    on e.id = rr.reward_budget_epoch_id
), paid as (
  select
    rb.id as reward_round_id,
    count(*) filter (where rp.status='PAID' and rp.paid_at is not null) as paid_referral_rewards,
    count(distinct rp.recipient_wallet) filter (where rp.status='PAID' and rp.paid_at is not null) as rewarded_inviters,
    coalesce(sum(rp.amount_wei) filter (where rp.status='PAID' and rp.paid_at is not null), 0) as paid_b3tr_wei
  from round_bindings rb
  left join public.reward_payouts rp on rp.round_id = rb.id
  group by rb.id
)
select
  a.id as allocation_receipt_id,
  a.network,
  a.app_id,
  a.vebetter_round_id,
  a.claim_tx_id,
  a.claim_block_number,
  a.claim_block_timestamp,
  a.total_amount_wei as total_app_allocation_wei,
  a.team_allocation_amount_wei,
  a.rewards_allocation_amount_wei as reward_pool_allocation_wei,
  a.unallocated_amount_wei,
  a.total_amount_wei / 1000000000000000000::numeric as total_app_allocation_b3tr,
  a.team_allocation_amount_wei / 1000000000000000000::numeric as team_allocation_b3tr,
  a.rewards_allocation_amount_wei / 1000000000000000000::numeric as reward_pool_allocation_b3tr,
  rb.id as reward_round_id,
  rb.status as reward_round_status,
  rb.opening_carryover_wei,
  rb.observed_pool_balance_wei,
  rb.reserved_before_round_wei,
  rb.distributable_wei,
  rb.eligible_count,
  rb.per_reward_wei,
  rb.remainder_wei as closing_carryover_wei,
  rb.created_at as reward_round_created_at,
  rb.completed_at as reward_round_completed_at,
  coalesce(p.paid_referral_rewards,0::bigint) as paid_referral_rewards,
  coalesce(p.rewarded_inviters,0::bigint) as rewarded_inviters,
  coalesce(p.paid_b3tr_wei,0::numeric) as paid_b3tr_wei,
  coalesce(p.paid_b3tr_wei,0::numeric) / 1000000000000000000::numeric as paid_b3tr,
  case
    when rb.id is null then 'ALLOCATED_NOT_PREPARED'
    when rb.status='COMPLETED'
      and coalesce(p.paid_referral_rewards,0::bigint)=rb.eligible_count
      and coalesce(p.paid_b3tr_wei,0::numeric)=rb.distributable_wei then 'SETTLED'
    else rb.status
  end as accounting_status,
  a.observed_at
from public.vebetter_round_allocations a
left join round_bindings rb
  on rb.effective_allocation_receipt_id = a.id
left join paid p
  on p.reward_round_id = rb.id
order by a.vebetter_round_id desc, rb.id asc;

revoke all on public.operator_vebetter_round_accounting from public, anon, authenticated;
grant select on public.operator_vebetter_round_accounting to service_role;

create or replace view public.operator_reward_data_quality
with (security_invoker = true)
as
with networks(network) as (
  values ('mainnet'::text), ('testnet'::text), ('testnet-staging'::text)
), checks as (
  select
    n.network,
    (select count(*)
       from public.reward_payouts rp
       join public.reward_rounds rr on rr.id=rp.round_id
      where rr.network=n.network
        and rp.status='PAID'
        and not exists (select 1 from public.reward_receipts r where r.payout_id=rp.id)) as paid_payouts_without_receipt,
    (select count(*)
       from public.reward_receipts r
       join public.reward_payouts rp on rp.id=r.payout_id
       join public.reward_rounds rr on rr.id=rp.round_id
      where rr.network=n.network
        and (rp.status<>'PAID' or rp.tx_id is distinct from r.tx_id or rp.amount_wei is distinct from r.amount_wei or rp.recipient_wallet is distinct from r.recipient_wallet)) as receipt_evidence_mismatches,
    (select count(*)
       from public.reward_payout_transaction_settlements s
      where s.network=n.network
        and not exists (select 1 from public.reward_payout_transaction_submissions sub where sub.manifest_id=s.manifest_id and sub.tx_id=s.tx_id)) as settlements_without_submission,
    (select count(*)
       from public.reward_rounds rr
      where rr.network=n.network
        and rr.reward_budget_epoch_id is not null
        and not exists (select 1 from public.reward_budget_epochs e where e.id=rr.reward_budget_epoch_id)) as predictive_rounds_without_epoch,
    (select count(*)
       from public.reward_rounds rr
      where rr.network=n.network
        and exists (select 1 from public.reward_payouts rp where rp.round_id=rr.id)
        and ((select count(*) from public.reward_payouts rp where rp.round_id=rr.id) <> rr.eligible_count
          or (select coalesce(sum(rp.amount_wei),0) from public.reward_payouts rp where rp.round_id=rr.id) <> rr.distributable_wei)) as round_payout_accounting_mismatches,
    (select count(*)
       from public.reward_payouts rp
       join public.reward_rounds rr on rr.id=rp.round_id
      where rr.network=n.network
        and rp.status='PAID'
        and not exists (select 1 from public.reward_payout_transaction_settlements s where s.round_id=rr.id and s.tx_id=rp.tx_id)) as paid_payouts_without_settlement
  from networks n
)
select *,
  paid_payouts_without_receipt=0
  and receipt_evidence_mismatches=0
  and settlements_without_submission=0
  and predictive_rounds_without_epoch=0
  and round_payout_accounting_mismatches=0
  and paid_payouts_without_settlement=0 as is_clean
from checks
order by network;

revoke all on public.operator_reward_data_quality from public, anon, authenticated;
grant select on public.operator_reward_data_quality to service_role;

commit;
