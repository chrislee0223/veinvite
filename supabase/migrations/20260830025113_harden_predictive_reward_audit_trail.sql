create or replace function public.log_reward_payout_status_event()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.reward_payout_status_events(
      payout_id, round_id, invite_code, from_status, to_status,
      attempt_count, tx_id, error_message, paid_at
    ) values (
      new.id, new.round_id, new.invite_code, null, new.status,
      new.attempt_count, new.tx_id, new.error_message, new.paid_at
    );
    return new;
  end if;

  if new.status is distinct from old.status
     or new.attempt_count is distinct from old.attempt_count
     or new.tx_id is distinct from old.tx_id
     or new.error_message is distinct from old.error_message
     or new.paid_at is distinct from old.paid_at then
    insert into public.reward_payout_status_events(
      payout_id, round_id, invite_code, from_status, to_status,
      attempt_count, tx_id, error_message, paid_at
    ) values (
      new.id, new.round_id, new.invite_code, old.status, new.status,
      new.attempt_count, new.tx_id, new.error_message, new.paid_at
    );
  end if;

  return new;
end;
$$;

revoke all on function public.log_reward_payout_status_event() from public, anon, authenticated;
