-- Read-optimized operator projections. Raw invitation, authentication and usage
-- tables remain authoritative; these rows exist only to make operator status
-- reads bounded and cheap as VeInvite grows.

begin;

create table if not exists public.operator_fast_wallets (
  wallet_address text primary key,
  first_seen_at timestamptz not null,
  last_seen_at timestamptz not null,
  updated_at timestamptz not null default now(),
  constraint operator_fast_wallets_address_check
    check (wallet_address ~ '^0x[0-9a-f]{40}$')
);

create table if not exists public.operator_fast_wallet_days (
  usage_date date not null,
  wallet_address text not null,
  first_seen_at timestamptz not null,
  last_seen_at timestamptz not null,
  updated_at timestamptz not null default now(),
  primary key (usage_date, wallet_address),
  constraint operator_fast_wallet_days_address_check
    check (wallet_address ~ '^0x[0-9a-f]{40}$')
);

create table if not exists public.operator_fast_invitations (
  invitation_id uuid primary key,
  invite_code text not null unique,
  inviter_wallet text not null,
  invitee_wallet text,
  status text not null,
  funnel_bucket text not null,
  entry_class text,
  eligibility_outcome text,
  is_valid_participant boolean not null,
  apps_3_plus boolean not null,
  rewards_3_plus boolean not null,
  vot3_complete boolean not null,
  vote_complete boolean not null,
  all_missions_complete boolean not null,
  source_updated_at timestamptz not null,
  projected_at timestamptz not null default now()
);

create table if not exists public.operator_fast_usage_visitors (
  usage_date date not null,
  visitor_key text not null,
  session_count bigint not null default 0 check (session_count >= 0),
  wallet_connected boolean not null default false,
  returning_visitor boolean not null default false,
  engaged_sessions bigint not null default 0 check (engaged_sessions >= 0),
  view_count bigint not null default 0 check (view_count >= 0),
  total_active_seconds bigint not null default 0 check (total_active_seconds >= 0),
  current_locale text not null,
  last_seen_at timestamptz not null,
  excluded boolean not null default false,
  projected_at timestamptz not null default now(),
  primary key (usage_date, visitor_key),
  constraint operator_fast_usage_visitors_key_check
    check (visitor_key ~ '^[0-9a-f]{64}$'),
  constraint operator_fast_usage_visitors_locale_check
    check (current_locale ~ '^[a-z]{2,3}(-[a-z]{2})?$')
);

create table if not exists public.operator_fast_reconciliation_log (
  id bigint generated by default as identity primary key,
  usage_date date not null,
  metric_rule_version text not null,
  matches boolean not null,
  fast_snapshot jsonb not null,
  source_snapshot jsonb not null,
  details jsonb not null default '{}'::jsonb,
  checked_at timestamptz not null default now()
);

create index if not exists operator_fast_wallet_days_wallet_idx
  on public.operator_fast_wallet_days (wallet_address, usage_date desc);
create index if not exists operator_fast_invitations_funnel_idx
  on public.operator_fast_invitations (funnel_bucket);
create index if not exists operator_fast_invitations_entry_idx
  on public.operator_fast_invitations (entry_class)
  where is_valid_participant;
create index if not exists operator_fast_usage_visitors_date_visible_idx
  on public.operator_fast_usage_visitors (usage_date, last_seen_at desc)
  where excluded = false;
create index if not exists operator_fast_usage_visitors_date_locale_idx
  on public.operator_fast_usage_visitors (usage_date, current_locale)
  where excluded = false;
create index if not exists operator_fast_reconciliation_log_checked_idx
  on public.operator_fast_reconciliation_log (checked_at desc);

alter table public.operator_fast_wallets enable row level security;
alter table public.operator_fast_wallet_days enable row level security;
alter table public.operator_fast_invitations enable row level security;
alter table public.operator_fast_usage_visitors enable row level security;
alter table public.operator_fast_reconciliation_log enable row level security;

revoke all on table public.operator_fast_wallets from public, anon, authenticated;
revoke all on table public.operator_fast_wallet_days from public, anon, authenticated;
revoke all on table public.operator_fast_invitations from public, anon, authenticated;
revoke all on table public.operator_fast_usage_visitors from public, anon, authenticated;
revoke all on table public.operator_fast_reconciliation_log from public, anon, authenticated;
grant select, insert, update, delete on table public.operator_fast_wallets to service_role;
grant select, insert, update, delete on table public.operator_fast_wallet_days to service_role;
grant select, insert, update, delete on table public.operator_fast_invitations to service_role;
grant select, insert, update, delete on table public.operator_fast_usage_visitors to service_role;
grant select, insert on table public.operator_fast_reconciliation_log to service_role;
grant usage, select on sequence public.operator_fast_reconciliation_log_id_seq to service_role;

create or replace function public.sync_operator_fast_wallet_projection()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_wallet text := lower(btrim(new.wallet_address));
  v_day date := (new.created_at at time zone 'Asia/Seoul')::date;
begin
  if v_wallet !~ '^0x[0-9a-f]{40}$' then return new; end if;

  insert into public.operator_fast_wallets (
    wallet_address, first_seen_at, last_seen_at, updated_at
  ) values (v_wallet, new.created_at, new.created_at, clock_timestamp())
  on conflict (wallet_address) do update
  set first_seen_at = least(public.operator_fast_wallets.first_seen_at, excluded.first_seen_at),
      last_seen_at = greatest(public.operator_fast_wallets.last_seen_at, excluded.last_seen_at),
      updated_at = clock_timestamp();

  insert into public.operator_fast_wallet_days (
    usage_date, wallet_address, first_seen_at, last_seen_at, updated_at
  ) values (v_day, v_wallet, new.created_at, new.created_at, clock_timestamp())
  on conflict (usage_date, wallet_address) do update
  set first_seen_at = least(public.operator_fast_wallet_days.first_seen_at, excluded.first_seen_at),
      last_seen_at = greatest(public.operator_fast_wallet_days.last_seen_at, excluded.last_seen_at),
      updated_at = clock_timestamp();

  return new;
end;
$$;

