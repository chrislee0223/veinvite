create or replace function public.sync_operator_fast_usage_projection()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  d date := (new.started_at at time zone 'Asia/Seoul')::date;
  x boolean;
begin
  select exists (
    select 1 from public.app_usage_excluded_visitors e
    where e.visitor_key = new.visitor_key
  ) into x;

  insert into public.operator_fast_usage_visitors (
    usage_date, visitor_key, session_count, wallet_connected,
    returning_visitor, engaged_sessions, view_count, total_active_seconds,
    current_locale, last_seen_at, excluded, projected_at
  )
  select
    d,
    s.visitor_key,
    count(*)::bigint,
    bool_or(s.wallet_connected),
    bool_or(s.returning_visitor),
    count(*) filter (where s.active_seconds >= 30)::bigint,
    coalesce(sum(s.view_count), 0)::bigint,
    coalesce(sum(s.active_seconds), 0)::bigint,
    (array_agg(
      s.current_locale
      order by s.last_seen_at desc, s.updated_at desc, s.session_id desc
    ))[1],
    max(s.last_seen_at),
    x,
    clock_timestamp()
  from public.app_usage_sessions s
  where s.visitor_key = new.visitor_key
    and (s.started_at at time zone 'Asia/Seoul')::date = d
  group by s.visitor_key
  on conflict (usage_date, visitor_key) do update
  set session_count = excluded.session_count,
      wallet_connected = excluded.wallet_connected,
      returning_visitor = excluded.returning_visitor,
      engaged_sessions = excluded.engaged_sessions,
      view_count = excluded.view_count,
      total_active_seconds = excluded.total_active_seconds,
      current_locale = excluded.current_locale,
      last_seen_at = excluded.last_seen_at,
      excluded = excluded.excluded,
      projected_at = clock_timestamp();

  return new;
end;
$$;

