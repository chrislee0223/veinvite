create or replace function public.rebuild_operator_fast_projections()
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_wallets bigint;
  v_days bigint;
  v_invitations bigint;
  v_usage bigint;
  v_invitation_id uuid;
begin
  delete from public.operator_fast_wallets;
  delete from public.operator_fast_wallet_days;
  delete from public.operator_fast_invitations;
  delete from public.operator_fast_usage_visitors;

  with e as (
    select lower(btrim(wallet_address)) as wallet_address, created_at as occurred_at
    from public.wallet_auth_sessions
    where lower(btrim(wallet_address)) ~ '^0x[0-9a-f]{40}$'
    union
    select lower(btrim(wallet_address)), occurred_at
    from public.veinvite_event_ledger
    where event_type = 'WALLET_AUTHENTICATED'
      and wallet_address is not null
      and lower(btrim(wallet_address)) ~ '^0x[0-9a-f]{40}$'
  )
  insert into public.operator_fast_wallets
  select wallet_address, min(occurred_at), max(occurred_at), clock_timestamp()
  from e group by wallet_address;
  get diagnostics v_wallets = row_count;

  with e as (
    select lower(btrim(wallet_address)) as wallet_address, created_at as occurred_at
    from public.wallet_auth_sessions
    where lower(btrim(wallet_address)) ~ '^0x[0-9a-f]{40}$'
    union
    select lower(btrim(wallet_address)), occurred_at
    from public.veinvite_event_ledger
    where event_type = 'WALLET_AUTHENTICATED'
      and wallet_address is not null
      and lower(btrim(wallet_address)) ~ '^0x[0-9a-f]{40}$'
  )
  insert into public.operator_fast_wallet_days
  select
    (occurred_at at time zone 'Asia/Seoul')::date,
    wallet_address,
    min(occurred_at),
    max(occurred_at),
    clock_timestamp()
  from e group by 1, 2;
  get diagnostics v_days = row_count;

  for v_invitation_id in select id from public.invitations loop
    perform public.sync_operator_fast_invitation_projection(v_invitation_id);
  end loop;
  select count(*) into v_invitations from public.operator_fast_invitations;

  insert into public.operator_fast_usage_visitors
  select
    (s.started_at at time zone 'Asia/Seoul')::date,
    s.visitor_key,
    count(*)::bigint,
    bool_or(s.wallet_connected),
    bool_or(s.returning_visitor),
    count(*) filter (where s.active_seconds >= 30)::bigint,
    coalesce(sum(s.view_count), 0)::bigint,
    coalesce(sum(s.active_seconds), 0)::bigint,
    (array_agg(
      s.current_locale
      order by s.last_seen_at desc, s.updated_at desc, s.session_id desc
    ))[1],
    max(s.last_seen_at),
    exists (
      select 1 from public.app_usage_excluded_visitors x
      where x.visitor_key = s.visitor_key
    ),
    clock_timestamp()
  from public.app_usage_sessions s
  group by 1, s.visitor_key;
  get diagnostics v_usage = row_count;

  return jsonb_build_object(
    'wallets', v_wallets,
    'walletDays', v_days,
    'invitations', v_invitations,
    'usageVisitors', v_usage,
    'rebuiltAt', clock_timestamp()
  );
end;
$$;

create or replace function public.read_operator_fast_status(
  p_usage_date date default ((now() at time zone 'Asia/Seoul')::date)
)
returns jsonb
language sql
stable
security invoker
set search_path = public
as $$
with x as (
  select wallet_address from public.analytics_excluded_wallets where active
), vi as (
  select p.*
  from public.operator_fast_invitations p
  where not exists (
    select 1 from x
    where wallet_address = p.inviter_wallet
       or wallet_address = p.invitee_wallet
  )
), im as (
  select
    count(*)::bigint as total,
    count(*) filter (where funnel_bucket = 'PENDING_ACCEPTANCE')::bigint as pending,
    count(*) filter (where funnel_bucket in ('INELIGIBLE_LIVE','INELIGIBLE_LEGACY'))::bigint as ineligible,
    count(*) filter (where funnel_bucket = 'CANCELLED_BY_INVITER')::bigint as cancelled,
    count(*) filter (where funnel_bucket = 'LEGACY_UNCLASSIFIED')::bigint as legacy,
    count(*) filter (where is_valid_participant)::bigint as valid,
    count(*) filter (where is_valid_participant and entry_class = 'NEW')::bigint as new_count,
    count(*) filter (where is_valid_participant and entry_class = 'RETURNING')::bigint as returning_count,
    count(*) filter (where apps_3_plus)::bigint as apps,
    count(*) filter (where rewards_3_plus)::bigint as rewards,
    count(*) filter (where vot3_complete)::bigint as vot3,
    count(*) filter (where vote_complete)::bigint as vote,
    count(*) filter (where all_missions_complete)::bigint as complete
  from vi
), u as (
  select
    count(*)::bigint as uv,
    count(*) filter (where not returning_visitor)::bigint as nv,
    count(*) filter (where returning_visitor)::bigint as rv,
    coalesce(sum(session_count),0)::bigint as sessions,
    count(*) filter (where wallet_connected)::bigint as connected,
    coalesce(sum(engaged_sessions),0)::bigint as engaged,
    coalesce(sum(view_count),0)::bigint as views,
    coalesce(sum(total_active_seconds),0)::bigint as seconds,
    case when coalesce(sum(session_count),0)=0 then 0::numeric
      else round(coalesce(sum(total_active_seconds),0)::numeric/sum(session_count)::numeric,1)
    end as avg_seconds,
    max(last_seen_at) as latest
  from public.operator_fast_usage_visitors
  where usage_date = p_usage_date and not excluded
), l as (
  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'locale', current_locale,
        'uniqueVisitors', n,
        'sessions', s,
        'totalActiveSeconds', a
      ) order by n desc, current_locale
    ), '[]'::jsonb
  ) as value
  from (
    select
      current_locale,
      count(*)::bigint as n,
      coalesce(sum(session_count),0)::bigint as s,
      coalesce(sum(total_active_seconds),0)::bigint as a
    from public.operator_fast_usage_visitors
    where usage_date = p_usage_date and not excluded
    group by current_locale
  ) q
)
select jsonb_build_object(
  'metricRuleVersion','operator-fast-v1',
  'timezone','Asia/Seoul',
  'usageDate',p_usage_date,
  'generatedAt',now(),
  'users',jsonb_build_object(
    'authenticatedWalletsEver',(select count(*) from public.operator_fast_wallets w where not exists(select 1 from x where wallet_address=w.wallet_address)),
    'authenticatedWalletsToday',(select count(*) from public.operator_fast_wallet_days w where usage_date=p_usage_date and not exists(select 1 from x where wallet_address=w.wallet_address)),
    'invitationsTotal',im.total,
    'pendingAcceptance',im.pending,
    'ineligibleRejections',im.ineligible,
    'cancelledByInviter',im.cancelled,
    'legacyUnclassified',im.legacy,
    'validParticipants',im.valid,
    'new',im.new_count,
    'returning',im.returning_count,
    'apps3Plus',im.apps,
    'rewards3Plus',im.rewards,
    'vot3Complete',im.vot3,
    'voteComplete',im.vote,
    'allMissionsComplete',im.complete
  ),
  'visitors',jsonb_build_object(
    'uniqueVisitors',u.uv,
    'newVisitors',u.nv,
    'returningVisitors',u.rv,
    'sessions',u.sessions,
    'walletConnectedVisitors',u.connected,
    'engagedSessions',u.engaged,
    'viewCount',u.views,
    'totalActiveSeconds',u.seconds,
    'averageActiveSeconds',u.avg_seconds,
    'latestSeenAt',u.latest,
    'locales',l.value
  )
)
from im cross join u cross join l;
$$;

