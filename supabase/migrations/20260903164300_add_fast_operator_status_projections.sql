create or replace function public.sync_operator_fast_invitation_projection(
  p_invitation_id uuid
)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  r record;
  b text;
  c text;
  o text;
  valid boolean;
begin
  select
    i.id,
    i.invite_code,
    lower(btrim(i.inviter_wallet)) as inviter_wallet,
    case when i.invitee_wallet is null then null else lower(btrim(i.invitee_wallet)) end as invitee_wallet,
    i.status,
    i.apps_completed,
    i.rewards_received,
    i.vot3_converted,
    i.vote_completed,
    i.apps_completed_block,
    i.vot3_converted_block,
    i.vote_completed_block,
    i.eligibility_check_id,
    i.ineligibility_check_id,
    i.updated_at,
    e.entry_class as modern_class,
    e.outcome as modern_outcome,
    l.entry_class as legacy_class,
    l.outcome as legacy_outcome
  into r
  from public.invitations i
  left join public.eligibility_check_events e on e.id = i.eligibility_check_id
  left join lateral (
    select x.entry_class, x.outcome
    from public.legacy_entry_classification_backfill x
    where x.invitation_id = i.id
      and x.classification_status = 'VERIFIED'
    order by x.recorded_at desc, x.id desc
    limit 1
  ) l on true
  where i.id = p_invitation_id;

  if not found then
    delete from public.operator_fast_invitations
    where invitation_id = p_invitation_id;
    return;
  end if;

  c := coalesce(r.modern_class, r.legacy_class);
  o := coalesce(r.modern_outcome, r.legacy_outcome);
  b := case
    when r.ineligibility_check_id is not null then 'INELIGIBLE_LIVE'
    when r.eligibility_check_id is null
      and r.legacy_outcome = 'EXISTING_VEBETTER_USER'
      and r.legacy_class = 'ACTIVE_EXISTING' then 'INELIGIBLE_LEGACY'
    when r.eligibility_check_id is not null
      and r.modern_outcome = 'ELIGIBLE'
      and r.modern_class in ('NEW', 'RETURNING') then 'ACCEPTED_MODERN'
    when r.eligibility_check_id is null
      and r.invitee_wallet is not null
      and r.legacy_outcome = 'ELIGIBLE'
      and r.legacy_class in ('NEW', 'RETURNING') then 'ACCEPTED_LEGACY'
    when r.status = 'PENDING_ACCEPTANCE' then 'PENDING_ACCEPTANCE'
    when r.status = 'CANCELLED' then 'CANCELLED_BY_INVITER'
    when r.invitee_wallet is not null and r.eligibility_check_id is null then 'LEGACY_UNCLASSIFIED'
    else 'OTHER'
  end;
  valid := b in ('ACCEPTED_MODERN', 'ACCEPTED_LEGACY');

  insert into public.operator_fast_invitations (
    invitation_id, invite_code, inviter_wallet, invitee_wallet, status,
    funnel_bucket, entry_class, eligibility_outcome, is_valid_participant,
    apps_3_plus, rewards_3_plus, vot3_complete, vote_complete,
    all_missions_complete, source_updated_at, projected_at
  ) values (
    r.id, r.invite_code, r.inviter_wallet, r.invitee_wallet, r.status,
    b, c, o, valid,
    valid and coalesce(r.apps_completed, 0) >= 3
      and (r.eligibility_check_id is null or r.apps_completed_block is not null),
    valid and coalesce(r.rewards_received, 0) >= 3,
    valid and coalesce(r.vot3_converted, false)
      and (r.eligibility_check_id is null or r.vot3_converted_block is not null),
    valid and coalesce(r.vote_completed, false)
      and (r.eligibility_check_id is null or r.vote_completed_block is not null),
    valid and coalesce(r.apps_completed, 0) >= 3
      and coalesce(r.rewards_received, 0) >= 3
      and coalesce(r.vot3_converted, false)
      and coalesce(r.vote_completed, false)
      and (
        r.eligibility_check_id is null
        or (
          r.apps_completed_block is not null
          and r.vot3_converted_block is not null
          and r.vote_completed_block is not null
        )
      ),
    r.updated_at, clock_timestamp()
  )
  on conflict (invitation_id) do update
  set invite_code = excluded.invite_code,
      inviter_wallet = excluded.inviter_wallet,
      invitee_wallet = excluded.invitee_wallet,
      status = excluded.status,
      funnel_bucket = excluded.funnel_bucket,
      entry_class = excluded.entry_class,
      eligibility_outcome = excluded.eligibility_outcome,
      is_valid_participant = excluded.is_valid_participant,
      apps_3_plus = excluded.apps_3_plus,
      rewards_3_plus = excluded.rewards_3_plus,
      vot3_complete = excluded.vot3_complete,
      vote_complete = excluded.vote_complete,
      all_missions_complete = excluded.all_missions_complete,
      source_updated_at = excluded.source_updated_at,
      projected_at = clock_timestamp();
end;
$$;

