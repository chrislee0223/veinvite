-- Keep only verified physical-pool observations in the active display
-- pipeline. Historical reward_forecast_snapshots are retained read-only for
-- audit; their obsolete per-recipient figures must never drive the Home UI.
create table if not exists public.reward_pool_observations (
  id bigint generated by default as identity primary key,
  network text not null check (network in ('mainnet', 'testnet', 'testnet-staging')),
  app_id text not null check (app_id ~ '^0x[0-9a-f]{64}$'),
  generated_at timestamptz not null,
  observed_pool_balance_wei numeric(78,0) not null
    check (observed_pool_balance_wei >= 0),
  basis_allocation_round_id bigint not null
    check (basis_allocation_round_id > 0),
  projected_funding_round_id bigint not null
    check (projected_funding_round_id > 0),
  input_snapshot jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
comment on table public.reward_pool_observations is
  'Server-only effective VeChain pool observations. No per-user estimates, reward entitlements, signatures, or payout authority.';
create index if not exists reward_pool_observations_latest_idx
  on public.reward_pool_observations(network, app_id, generated_at desc, id desc);

alter table public.reward_pool_observations enable row level security;
revoke all on public.reward_pool_observations from public, anon, authenticated;
grant select, insert on public.reward_pool_observations to service_role;
grant usage, select on sequence public.reward_pool_observations_id_seq to service_role;

-- One-time continuity seed; never copy a legacy calculated reward amount.
insert into public.reward_pool_observations
  (network, app_id, generated_at, observed_pool_balance_wei,
   basis_allocation_round_id, projected_funding_round_id, input_snapshot)
select distinct on (s.network, s.app_id)
  s.network, s.app_id, s.generated_at, s.observed_pool_balance_wei,
  s.basis_allocation_round_id, s.projected_funding_round_id, s.input_snapshot
from public.reward_forecast_snapshots s
where not exists (
  select 1 from public.reward_pool_observations p
  where p.network=s.network and p.app_id=s.app_id
)
order by s.network, s.app_id, s.generated_at desc, s.id desc;

-- Both quote readers depend on a fresh on-chain physical observation, but
-- MUST NOT depend on legacy recipient-forecast rows or their price fields.
do $migration$
declare
  v_proc regprocedure;
  v_definition text;
  v_rewritten text;
begin
  foreach v_proc in array array[
    'public.read_reward_shared_pool_capacity_shadow_v1(text,text)'::regprocedure,
    'public.read_reward_elastic_public_scenarios_v1(text,text)'::regprocedure
  ]
  loop
    v_definition := pg_get_functiondef(v_proc::oid);
    if position('public.reward_forecast_snapshots' in v_definition) = 0 then
      raise exception 'Pool reader no longer uses the expected old source: %', v_proc;
    end if;
    v_rewritten := replace(
      v_definition,
      'public.reward_forecast_snapshots',
      'public.reward_pool_observations'
    );
    execute v_rewritten;
  end loop;
end
$migration$;

