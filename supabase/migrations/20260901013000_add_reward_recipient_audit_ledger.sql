create table if not exists public.reward_recipient_audit_ledger (
  id bigint generated by default as identity primary key,
  receipt_id bigint not null unique references public.reward_receipts(id) on delete restrict,
  payout_id bigint references public.reward_payouts(id) on delete restrict,
  settlement_id bigint,
  network text not null,
  vebetter_round_id bigint not null,
  invite_code text not null,
  recipient_wallet text not null,
  invitee_wallet text,
  amount_wei numeric(78, 0) not null check (amount_wei > 0),
  tx_id text not null,
  paid_at timestamptz not null,
  entry_class text,
  sybil_status_at_payout text,
  sybil_risk_level_at_payout text,
  sybil_risk_score_at_payout integer,
  sybil_reason_at_payout text,
  sybil_checked_at_payout timestamptz,
  sybil_source_at_payout text,
  context_complete boolean not null default false,
  created_at timestamptz not null default now(),
  check (recipient_wallet = lower(btrim(recipient_wallet))),
  check (invitee_wallet is null or invitee_wallet = lower(btrim(invitee_wallet)))
);

create index if not exists reward_recipient_audit_ledger_wallet_paid_idx
  on public.reward_recipient_audit_ledger (network, recipient_wallet, paid_at desc);

create index if not exists reward_recipient_audit_ledger_invitee_idx
  on public.reward_recipient_audit_ledger (network, invitee_wallet)
  where invitee_wallet is not null;

create index if not exists reward_recipient_audit_ledger_round_idx
  on public.reward_recipient_audit_ledger (network, vebetter_round_id, paid_at desc);

alter table public.reward_recipient_audit_ledger enable row level security;
revoke all on table public.reward_recipient_audit_ledger from public, anon, authenticated;
grant select on table public.reward_recipient_audit_ledger to service_role;

create or replace function public.prevent_reward_recipient_audit_mutation()
returns trigger
language plpgsql
set search_path to 'public'
as $$
begin
  raise exception 'reward recipient audit history is append-only';
end;
$$;

revoke all on function public.prevent_reward_recipient_audit_mutation() from public, anon, authenticated;

create trigger reward_recipient_audit_ledger_immutable
before update or delete on public.reward_recipient_audit_ledger
for each row
execute function public.prevent_reward_recipient_audit_mutation();

create or replace function public.capture_reward_recipient_audit_ledger()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $$
declare
  v_invitation public.invitations%rowtype;
  v_entry_class text;
begin
  select i.*
    into v_invitation
    from public.invitations i
   where i.invite_code = new.invite_code
   limit 1;

  select q.entry_class
    into v_entry_class
    from public.reward_queue_entries q
   where q.invite_code = new.invite_code
     and q.network = new.network
   order by q.id desc
   limit 1;

  insert into public.reward_recipient_audit_ledger (
    receipt_id,
    payout_id,
    settlement_id,
    network,
    vebetter_round_id,
    invite_code,
    recipient_wallet,
    invitee_wallet,
    amount_wei,
    tx_id,
    paid_at,
    entry_class,
    sybil_status_at_payout,
    sybil_risk_level_at_payout,
    sybil_risk_score_at_payout,
    sybil_reason_at_payout,
    sybil_checked_at_payout,
    sybil_source_at_payout,
    context_complete
  ) values (
    new.id,
    new.payout_id,
    new.settlement_id,
    new.network,
    new.vebetter_round_id,
    new.invite_code,
    lower(btrim(new.recipient_wallet)),
    case
      when v_invitation.id is null or v_invitation.invitee_wallet is null then null
      else lower(btrim(v_invitation.invitee_wallet))
    end,
    new.amount_wei,
    new.tx_id,
    new.paid_at,
    v_entry_class,
    v_invitation.sybil_status,
    v_invitation.sybil_risk_level,
    v_invitation.sybil_risk_score,
    v_invitation.sybil_reason,
    v_invitation.sybil_checked_at,
    v_invitation.sybil_source,
    v_invitation.id is not null
      and v_invitation.invitee_wallet is not null
      and lower(btrim(v_invitation.inviter_wallet)) = lower(btrim(new.recipient_wallet))
  )
  on conflict (receipt_id) do nothing;

  return new;
end;
$$;

revoke all on function public.capture_reward_recipient_audit_ledger() from public, anon, authenticated;

create trigger reward_receipts_capture_recipient_audit
  after insert on public.reward_receipts
  for each row
  execute function public.capture_reward_recipient_audit_ledger();

insert into public.reward_recipient_audit_ledger (
  receipt_id,
  payout_id,
  settlement_id,
  network,
  vebetter_round_id,
  invite_code,
  recipient_wallet,
  invitee_wallet,
  amount_wei,
  tx_id,
  paid_at,
  entry_class,
  sybil_status_at_payout,
  sybil_risk_level_at_payout,
  sybil_risk_score_at_payout,
  sybil_reason_at_payout,
  sybil_checked_at_payout,
  sybil_source_at_payout,
  context_complete
)
select
  r.id,
  r.payout_id,
  r.settlement_id,
  r.network,
  r.vebetter_round_id,
  r.invite_code,
  lower(btrim(r.recipient_wallet)),
  case when i.invitee_wallet is null then null else lower(btrim(i.invitee_wallet)) end,
  r.amount_wei,
  r.tx_id,
  r.paid_at,
  q.entry_class,
  i.sybil_status,
  i.sybil_risk_level,
  i.sybil_risk_score,
  i.sybil_reason,
  i.sybil_checked_at,
  i.sybil_source,
  i.id is not null
    and i.invitee_wallet is not null
    and lower(btrim(i.inviter_wallet)) = lower(btrim(r.recipient_wallet))
from public.reward_receipts r
left join public.invitations i
  on i.invite_code = r.invite_code
left join lateral (
  select qe.entry_class
    from public.reward_queue_entries qe
   where qe.invite_code = r.invite_code
     and qe.network = r.network
   order by qe.id desc
   limit 1
) q on true
on conflict (receipt_id) do nothing;

create table if not exists public.reward_recipient_risk_events (
  id bigint generated by default as identity primary key,
  network text not null,
  recipient_wallet text not null,
  risk_status text not null check (risk_status in ('CLEAR', 'WATCH', 'REVIEW', 'BLOCKED')),
  risk_category text not null check (risk_category in ('SYBIL', 'FARMING', 'MULTI_ACCOUNT', 'PATTERN', 'OTHER')),
  reason text not null check (char_length(btrim(reason)) between 12 and 1000),
  source text not null check (source in ('OPERATOR', 'AUTOMATED', 'VE_PASSPORT', 'PATTERN_ANALYSIS')),
  related_invite_code text,
  related_receipt_id bigint references public.reward_receipts(id) on delete restrict,
  evidence jsonb not null default '{}'::jsonb,
  recorded_by_wallet text,
  created_at timestamptz not null default now(),
  check (recipient_wallet = lower(btrim(recipient_wallet))),
  check (recorded_by_wallet is null or recorded_by_wallet = lower(btrim(recorded_by_wallet)))
);

create index if not exists reward_recipient_risk_events_wallet_idx
  on public.reward_recipient_risk_events (network, recipient_wallet, created_at desc, id desc);

