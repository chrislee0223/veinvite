create or replace view public.operator_reward_recipient_analytics
with (security_invoker = true)
as
with recipient_stats as (
  select
    l.network,
    l.recipient_wallet as wallet_address,
    count(*)::bigint as reward_count,
    count(distinct l.invite_code)::bigint as paid_referral_count,
    count(distinct l.vebetter_round_id)::bigint as paid_round_count,
    count(distinct l.invitee_wallet) filter (where l.invitee_wallet is not null)::bigint as unique_invitee_count,
    sum(l.amount_wei) as total_reward_wei,
    avg(l.amount_wei) as average_reward_wei,
    max(l.amount_wei) as highest_single_reward_wei,
    min(l.paid_at) as first_paid_at,
    max(l.paid_at) as last_paid_at,
    count(*) filter (where l.context_complete = false)::bigint as incomplete_context_count,
    count(*) filter (where l.sybil_status_at_payout in ('REVIEW', 'BLOCKED'))::bigint as payout_risk_flag_count
  from public.reward_recipient_audit_ledger l
  group by l.network, l.recipient_wallet
), latest_risk as (
  select distinct on (e.network, e.recipient_wallet)
    e.network,
    e.recipient_wallet,
    e.risk_status,
    e.risk_category,
    e.reason,
    e.source,
    e.created_at
  from public.reward_recipient_risk_events e
  order by e.network, e.recipient_wallet, e.created_at desc, e.id desc
)
select
  dense_rank() over (
    partition by s.network
    order by s.total_reward_wei desc, s.last_paid_at asc, s.wallet_address asc
  )::bigint as total_reward_rank,
  dense_rank() over (
    partition by s.network
    order by s.reward_count desc, s.total_reward_wei desc, s.wallet_address asc
  )::bigint as reward_count_rank,
  s.network,
  s.wallet_address,
  s.reward_count,
  s.paid_referral_count,
  s.paid_round_count,
  s.unique_invitee_count,
  s.total_reward_wei,
  s.average_reward_wei,
  s.highest_single_reward_wei,
  s.first_paid_at,
  s.last_paid_at,
  s.incomplete_context_count,
  s.payout_risk_flag_count,
  r.risk_status as latest_risk_status,
  r.risk_category as latest_risk_category,
  r.reason as latest_risk_reason,
  r.source as latest_risk_source,
  r.created_at as latest_risk_at
from recipient_stats s
left join latest_risk r
  on r.network = s.network
 and r.recipient_wallet = s.wallet_address;

revoke all on table public.operator_reward_recipient_analytics from public, anon, authenticated;
grant select on table public.operator_reward_recipient_analytics to service_role;

comment on table public.reward_recipient_audit_ledger is
  'Append-only per-payment audit ledger for reward recipients, including payout-time referral and Sybil context. It is populated automatically from finalized reward receipts.';

comment on table public.reward_recipient_risk_events is
  'Append-only operator/automated risk history for wallets that have received VeInvite rewards. Use WATCH/REVIEW/BLOCKED without rewriting historical payout records.';

comment on view public.operator_reward_recipient_analytics is
  'Operator-only recipient rankings and lifetime reward/risk summary. Supports ranking by total B3TR received or reward count while preserving payout-time audit context.';
