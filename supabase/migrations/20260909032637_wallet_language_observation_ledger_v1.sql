create table if not exists public.wallet_language_observation_events (
  id bigint generated by default as identity primary key,
  wallet_address text not null
    check (wallet_address ~ '^0x[0-9a-f]{40}$'),
  language_code text not null
    check (
      language_code ~ '^[a-z]{2,3}(-[a-z0-9]{2,8})*$'
      and char_length(language_code) <= 35
    ),
  language_source text not null
    check (
      language_source in (
        'browser_auto',
        'local_storage',
        'query_param',
        'wallet_preference',
        'manual_selection'
      )
    ),
  observed_at timestamptz not null,
  created_at timestamptz not null default clock_timestamp(),
  source_snapshot jsonb not null default '{}'::jsonb
    check (jsonb_typeof(source_snapshot) = 'object')
);

comment on table public.wallet_language_observation_events is
  'Append-only authenticated wallet display-language observations used only for near-activation attribution and operator analytics.';

alter table public.wallet_language_observation_events enable row level security;

revoke all on table public.wallet_language_observation_events
  from public, anon, authenticated;
grant select, insert on table public.wallet_language_observation_events
  to service_role;

revoke all on sequence public.wallet_language_observation_events_id_seq
  from public, anon, authenticated;
grant usage, select on sequence public.wallet_language_observation_events_id_seq
  to service_role;

create index if not exists wallet_language_observation_events_wallet_time_idx
  on public.wallet_language_observation_events (wallet_address, observed_at desc);

create index if not exists wallet_language_observation_events_time_idx
  on public.wallet_language_observation_events (observed_at desc);

drop trigger if exists wallet_language_observation_events_append_only
  on public.wallet_language_observation_events;
create trigger wallet_language_observation_events_append_only
before update or delete on public.wallet_language_observation_events
for each row execute function public.prevent_long_term_history_mutation();

create or replace function public.record_wallet_language_usage_v2(
  p_wallet_address text,
  p_language text,
  p_source text,
  p_observed_at timestamptz default clock_timestamp()
)
returns void
language plpgsql
security definer
set search_path to 'pg_catalog', 'public'
as $$
declare
  v_wallet text := lower(btrim(p_wallet_address));
  v_language text := lower(btrim(p_language));
  v_source text := lower(btrim(p_source));
  v_observed_at timestamptz := coalesce(p_observed_at, clock_timestamp());
begin
  if v_wallet !~ '^0x[0-9a-f]{40}$' then
    raise exception 'invalid wallet address';
  end if;

  if v_language !~ '^[a-z]{2,3}(-[a-z0-9]{2,8})*$'
     or char_length(v_language) > 35 then
    raise exception 'invalid language';
  end if;

  if v_source not in (
    'browser_auto',
    'local_storage',
    'query_param',
    'wallet_preference',
    'manual_selection'
  ) then
    raise exception 'invalid language source';
  end if;

  insert into public.wallet_language_observation_events (
    wallet_address,
    language_code,
    language_source,
    observed_at,
    source_snapshot
  ) values (
    v_wallet,
    v_language,
    v_source,
    v_observed_at,
    jsonb_build_object(
      'capture', 'record_wallet_language_usage_v2',
      'rawIpStored', false
    )
  );

  insert into public.wallet_language_usage (
    wallet_address,
    current_language,
    current_source,
    first_observed_at,
    last_observed_at,
    updated_at
  ) values (
    v_wallet,
    v_language,
    v_source,
    v_observed_at,
    v_observed_at,
    v_observed_at
  )
  on conflict (wallet_address) do update
  set current_language = case
        when public.wallet_language_source_priority(excluded.current_source)
             >= public.wallet_language_source_priority(public.wallet_language_usage.current_source)
          then excluded.current_language
        else public.wallet_language_usage.current_language
      end,
      current_source = case
        when public.wallet_language_source_priority(excluded.current_source)
             >= public.wallet_language_source_priority(public.wallet_language_usage.current_source)
          then excluded.current_source
        else public.wallet_language_usage.current_source
      end,
      last_observed_at = greatest(
        public.wallet_language_usage.last_observed_at,
        excluded.last_observed_at
      ),
      updated_at = greatest(
        public.wallet_language_usage.updated_at,
        excluded.updated_at
      );
end;
$$;

revoke all on function public.record_wallet_language_usage_v2(text,text,text,timestamptz)
  from public, anon, authenticated;
grant execute on function public.record_wallet_language_usage_v2(text,text,text,timestamptz)
  to service_role;

create or replace function public.capture_referral_activation_language_from_usage()
returns trigger
language plpgsql
set search_path to 'pg_catalog', 'public'
as $$
declare
  v_relationship public.referral_relationships%rowtype;
  v_language_code text;
  v_language_source text;
  v_language_observed_at timestamptz;
  v_fact_source text;
begin
  select r.* into v_relationship
  from public.referral_relationships r
  where r.child_wallet = new.wallet_address
  order by r.relationship_effective_at desc, r.id desc
  limit 1;

  if not found then
    return new;
  end if;

  select e.language_code, e.language_source, e.observed_at
    into v_language_code, v_language_source, v_language_observed_at
  from public.wallet_language_observation_events e
  where e.wallet_address = new.wallet_address
    and e.observed_at >= v_relationship.relationship_effective_at - interval '15 minutes'
    and e.observed_at <= v_relationship.relationship_effective_at + interval '15 minutes'
  order by
    public.wallet_language_source_priority(e.language_source) desc,
    abs(extract(epoch from (e.observed_at - v_relationship.relationship_effective_at))) asc,
    e.observed_at asc,
    e.id asc
  limit 1;

  if v_language_code is null or v_language_source is null then
    return new;
  end if;

  v_fact_source := case v_language_source
    when 'manual_selection' then 'MANUAL_SELECTION'
    when 'wallet_preference' then 'WALLET_PREFERENCE'
    when 'query_param' then 'QUERY_PARAM'
    when 'local_storage' then 'LOCAL_STORAGE'
    when 'browser_auto' then 'BROWSER_AUTO'
    else null
  end;

  if v_fact_source is null then
    return new;
  end if;

  insert into public.referral_activation_language_facts (
    relationship_id,
    source_invitation_id,
    language_code,
    language_source,
    observed_at,
    language_policy_version,
    source_snapshot
  ) values (
    v_relationship.id,
    v_relationship.source_invitation_id,
    v_language_code,
    v_fact_source,
    greatest(v_relationship.relationship_effective_at, v_language_observed_at),
    'wallet-language-event-near-activation-v3',
    jsonb_build_object(
      'capture', 'wallet_language_observation_event',
      'actualObservedAt', v_language_observed_at,
      'usageSource', v_language_source,
      'rawIpStored', false
    )
  ) on conflict (source_invitation_id) do nothing;

  return new;
end;
$$;

revoke all on function public.capture_referral_activation_language_from_usage()
  from public, anon, authenticated;
grant execute on function public.capture_referral_activation_language_from_usage()
  to service_role;

create or replace function public.capture_referral_activation_context()
returns trigger
language plpgsql
set search_path to 'pg_catalog', 'public'
as $$
declare
  v_country_code text;
  v_country_observed_at timestamptz;
  v_language_code text;
  v_language_source text;
  v_language_observed_at timestamptz;
  v_language_fact_source text;
begin
  select s.country_code, s.country_observed_at
    into v_country_code, v_country_observed_at
  from public.wallet_auth_sessions s
  where s.wallet_address = new.child_wallet
    and s.country_source = 'TRUSTED_EDGE'
    and s.country_code ~ '^[A-Z]{2}$'
    and s.country_observed_at is not null
    and s.country_observed_at >= new.relationship_effective_at - interval '15 minutes'
    and s.country_observed_at <= new.relationship_effective_at + interval '15 minutes'
  order by s.country_observed_at desc, s.id desc
  limit 1;

  if v_country_code is not null then
    insert into public.referral_activation_country_facts (
      relationship_id,
      source_invitation_id,
      country_code,
      country_source,
      observed_at,
      geo_policy_version,
      source_snapshot
    ) values (
      new.id,
      new.source_invitation_id,
      v_country_code,
      'TRUSTED_EDGE',
      new.relationship_effective_at,
      'wallet-auth-edge-v2',
      jsonb_build_object(
        'capture','wallet_auth_session',
        'countryObservedAt',v_country_observed_at,
        'rawIpStored',false
