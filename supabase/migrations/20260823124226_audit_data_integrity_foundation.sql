-- An impact event must describe the same invitation, invitee and network, and
-- must occur on-chain after the invitation boundary.
create or replace function public.validate_invite_impact_event()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_invitee text;
  v_activation_block bigint;
  v_activation_network text;
  v_apps_completed_block bigint;
begin
  select
    invitee_wallet,
    activation_block,
    activation_network,
    apps_completed_block
  into
    v_invitee,
    v_activation_block,
    v_activation_network,
    v_apps_completed_block
  from public.invitations
  where invite_code = new.invite_code;

  if not found then
    raise exception 'Invitation % does not exist', new.invite_code;
  end if;

  if v_invitee is null
     or lower(v_invitee) <> lower(new.wallet_address) then
    raise exception 'Impact wallet does not match invitation %', new.invite_code;
  end if;

  if v_activation_network is null
     or lower(v_activation_network) <> lower(new.network) then
    raise exception 'Impact network does not match invitation %', new.invite_code;
  end if;

  if v_activation_block is null
     or new.block_number < v_activation_block then
    raise exception 'Impact block predates invitation activation %', new.invite_code;
  end if;

  if new.event_type = 'ALLOCATION_VOTE'
     and (
       v_apps_completed_block is null
       or new.block_number < v_apps_completed_block
     ) then
    raise exception
      'Vote impact predates three-app checkpoint for invitation %',
      new.invite_code;
  end if;

  return new;
end;
$$;

revoke all on function public.validate_invite_impact_event()
  from public, anon, authenticated;

drop trigger if exists invite_impact_events_validate
  on public.invite_impact_events;
create trigger invite_impact_events_validate
before insert on public.invite_impact_events
for each row execute function public.validate_invite_impact_event();

create unique index if not exists invite_impact_events_one_reward_per_app_idx
