-- Audit ledgers are append-only. Application code may append facts but may not
-- silently rewrite the history used for operator answers or public reports.
create or replace function public.prevent_operator_ledger_mutation()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  raise exception '% is append-only', tg_table_name;
end;
$$;

revoke all on function public.prevent_operator_ledger_mutation()
  from public, anon, authenticated;

revoke update, delete, truncate on table public.sybil_review_events
  from service_role;
revoke update, delete, truncate on table public.invite_impact_events
  from service_role;
revoke update, delete, truncate on table public.eligibility_check_events
  from service_role;

drop trigger if exists sybil_review_events_append_only
  on public.sybil_review_events;
