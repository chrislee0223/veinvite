-- Persist the exact network and the entry-eligibility check that admitted an
-- invitee. Sync watermark fields are used by later reconciliation/reporting.
alter table public.invitations
  add column if not exists activation_network text,
  add column if not exists eligibility_check_id bigint,
  add column if not exists impact_last_synced_block bigint,
  add column if not exists impact_last_synced_at timestamptz,
  add column if not exists impact_sync_complete_at timestamptz;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'invitations_activation_network_check'
  ) then
    alter table public.invitations
      add constraint invitations_activation_network_check
      check (
        activation_network is null
        or activation_network in ('mainnet', 'testnet', 'testnet-staging')
      );
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'invitations_impact_sync_block_check'
  ) then
    alter table public.invitations
      add constraint invitations_impact_sync_block_check
      check (
        impact_last_synced_block is null
        or (
          impact_last_synced_block >= 0
          and (
            activation_block is null
            or impact_last_synced_block >= activation_block
          )
        )
      );
  end if;
end
$$;

create table if not exists public.eligibility_check_events (
  id bigint generated by default as identity primary key,
  invite_code text not null
    references public.invitations(invite_code)
    on update cascade
    on delete restrict,
  wallet_address text not null,
  network text not null,
  checked_block bigint not null,
  outcome text not null,
  prior_reward_tx_id text,
  prior_vote_tx_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),

  constraint eligibility_check_events_wallet_check
    check (wallet_address ~ '^0x[0-9a-f]{40}$'),
  constraint eligibility_check_events_network_check
    check (network in ('mainnet', 'testnet', 'testnet-staging')),
  constraint eligibility_check_events_block_check
    check (checked_block >= 0),
  constraint eligibility_check_events_outcome_check
    check (
      outcome in (
        'ELIGIBLE',
        'EXISTING_VEBETTER_USER',
        'REVIEW',
        'REJECTED'
      )
    ),
  constraint eligibility_check_events_reward_tx_check
    check (
      prior_reward_tx_id is null
      or prior_reward_tx_id ~ '^0x[0-9a-f]{64}$'
    ),
  constraint eligibility_check_events_vote_tx_check
    check (
      prior_vote_tx_id is null
      or prior_vote_tx_id ~ '^0x[0-9a-f]{64}$'
    ),
  constraint eligibility_check_events_details_check
    check (jsonb_typeof(details) = 'object')
);

create index if not exists eligibility_check_events_invite_created_idx
  on public.eligibility_check_events(invite_code, created_at desc);
create index if not exists eligibility_check_events_wallet_created_idx
  on public.eligibility_check_events(wallet_address, created_at desc);

