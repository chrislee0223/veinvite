begin;

create table if not exists public.operator_weekly_report_snapshots (
  id bigint generated by default as identity primary key,
  network text not null check (network in ('mainnet','testnet','testnet-staging')),
  week_start timestamptz not null,
  week_end timestamptz not null,
  version integer not null check (version >= 1),
  new_wallets_onboarded bigint not null check (new_wallets_onboarded >= 0),
  successful_referrals_completed bigint not null check (successful_referrals_completed >= 0),
  active_onboarded_wallets bigint not null check (active_onboarded_wallets >= 0),
  verified_onboarding_transactions bigint not null check (verified_onboarding_transactions >= 0),
  verified_dapp_reward_transactions bigint not null check (verified_dapp_reward_transactions >= 0),
  verified_dapp_reward_events bigint not null check (verified_dapp_reward_events >= 0),
  governance_vote_transactions bigint not null check (governance_vote_transactions >= 0),
  paid_referral_rewards bigint not null check (paid_referral_rewards >= 0),
  rewarded_wallets bigint not null check (rewarded_wallets >= 0),
  b3tr_distributed_wei numeric(78,0) not null check (b3tr_distributed_wei >= 0),
  source_view text not null default 'operator_public_weekly_impact',
  data_quality jsonb not null default '{}'::jsonb check (jsonb_typeof(data_quality)='object'),
  revision_reason text,
  created_at timestamptz not null default now(),
  unique(network,week_start,version),
  check (week_end = week_start + interval '7 days'),
  check (week_start = public.veinvite_utc_week_start(week_start)),
  check (version = 1 or (revision_reason is not null and length(btrim(revision_reason)) > 0))
);

alter table public.operator_weekly_report_snapshots enable row level security;

create index if not exists operator_weekly_report_snapshots_lookup_idx
  on public.operator_weekly_report_snapshots(network,week_start,version desc);

create trigger operator_weekly_report_snapshots_append_only
before update or delete on public.operator_weekly_report_snapshots
for each row execute function public.prevent_operator_ledger_mutation();

create or replace view public.operator_latest_weekly_report_snapshots as
select distinct on (network,week_start)
  id,network,week_start,week_end,version,
  new_wallets_onboarded,successful_referrals_completed,active_onboarded_wallets,
  verified_onboarding_transactions,verified_dapp_reward_transactions,
  verified_dapp_reward_events,governance_vote_transactions,
  paid_referral_rewards,rewarded_wallets,b3tr_distributed_wei,
  b3tr_distributed_wei / 1000000000000000000::numeric as b3tr_distributed,
  source_view,data_quality,revision_reason,created_at
from public.operator_weekly_report_snapshots
order by network,week_start,version desc;

create or replace function public.finalize_weekly_impact_report(
  p_network text,
  p_week_start timestamptz,
  p_revision_reason text default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_network text := lower(btrim(p_network));
  v_week_start timestamptz := public.veinvite_utc_week_start(p_week_start);
  v_week_end timestamptz := v_week_start + interval '7 days';
  v_current_week timestamptz := public.veinvite_utc_week_start(now());
  v_reporting_start timestamptz;
  v_reporting_network text;
  v_version integer;
  v_metrics record;
  v_quality record;
  v_snapshot_id bigint;
begin
  if v_network not in ('mainnet','testnet','testnet-staging') then
    raise exception 'unsupported network';
  end if;
  if p_week_start is null or p_week_start <> v_week_start then
    raise exception 'week_start must be Monday 00:00:00 UTC';
  end if;
  if v_week_start >= v_current_week then
    raise exception 'current or future week cannot be finalized';
  end if;

  select reporting_start_at,reporting_network
  into v_reporting_start,v_reporting_network
  from public.operator_reporting_config
  where id=1;

  if v_reporting_start is null then
    raise exception 'public reporting baseline is not enabled';
  end if;
  if v_reporting_network <> v_network then
    raise exception 'reporting network does not match requested network';
  end if;
  if v_week_end <= v_reporting_start then
    raise exception 'requested week is before public reporting baseline';
  end if;

  select * into v_quality
  from public.operator_weekly_data_quality q
  where q.network=v_network and q.week_start=v_week_start;

  if found and not v_quality.is_clean then
    raise exception 'weekly data-quality gate is not clean';
  end if;

  select * into v_metrics
  from public.operator_public_weekly_impact w
  where w.network=v_network and w.week_start=v_week_start;

  select coalesce(max(version),0)+1
  into v_version
  from public.operator_weekly_report_snapshots
  where network=v_network and week_start=v_week_start;

  if v_version > 1 and nullif(btrim(coalesce(p_revision_reason,'')),'') is null then
    raise exception 'revision reason is required after version 1';
  end if;

  insert into public.operator_weekly_report_snapshots(
    network,week_start,week_end,version,
    new_wallets_onboarded,successful_referrals_completed,active_onboarded_wallets,
    verified_onboarding_transactions,verified_dapp_reward_transactions,
    verified_dapp_reward_events,governance_vote_transactions,
    paid_referral_rewards,rewarded_wallets,b3tr_distributed_wei,
    data_quality,revision_reason
  ) values (
    v_network,v_week_start,v_week_end,v_version,
    coalesce(v_metrics.new_wallets_onboarded,0),
    coalesce(v_metrics.successful_referrals_completed,0),
    coalesce(v_metrics.active_onboarded_wallets,0),
    coalesce(v_metrics.verified_onboarding_transactions,0),
    coalesce(v_metrics.verified_dapp_reward_transactions,0),
    coalesce(v_metrics.verified_dapp_reward_events,0),
    coalesce(v_metrics.governance_vote_transactions,0),
    coalesce(v_metrics.paid_referral_rewards,0),
    coalesce(v_metrics.rewarded_wallets,0),
    coalesce(v_metrics.b3tr_distributed_wei,0),
    jsonb_build_object(
      'weekly_quality_row_found', v_quality is not null,
      'weekly_quality_clean', coalesce(v_quality.is_clean,true),
      'finalized_at', now()
    ),
    nullif(btrim(coalesce(p_revision_reason,'')),'')
  ) returning id into v_snapshot_id;

  return v_snapshot_id;
end;
$$;

revoke all on public.operator_weekly_report_snapshots from public,anon,authenticated;
revoke all on public.operator_latest_weekly_report_snapshots from public,anon,authenticated;
revoke all on function public.finalize_weekly_impact_report(text,timestamptz,text) from public,anon,authenticated;
grant select,insert on public.operator_weekly_report_snapshots to service_role;
grant select on public.operator_latest_weekly_report_snapshots to service_role;
grant execute on function public.finalize_weekly_impact_report(text,timestamptz,text) to service_role;

commit;