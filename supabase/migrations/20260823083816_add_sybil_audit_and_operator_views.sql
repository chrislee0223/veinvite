revoke all on table public.operator_referral_leaderboard from public, anon, authenticated;
grant select on table public.operator_sybil_watchlist to service_role;
grant select on table public.operator_reward_leaderboard to service_role;
grant select on table public.operator_referral_leaderboard to service_role;