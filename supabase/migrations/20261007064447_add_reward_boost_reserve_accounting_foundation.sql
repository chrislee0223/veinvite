CREATE OR REPLACE FUNCTION public.validate_reward_boost_reserve_ledger()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
declare
  v_source_receipt public.vebetter_round_allocations%rowtype;
  v_destination_receipt public.vebetter_round_allocations%rowtype;
  v_protection public.reward_boost_reserve_source_protections%rowtype;
  v_destination_plan public.reward_boost_reserve_destination_plans%rowtype;
  v_budget numeric(78,0) := 0;
  v_committed numeric(78,0) := 0;
  v_balance numeric(78,0) := 0;
  v_stress_reserve numeric(78,0) := 0;
  v_releaseable numeric(78,0) := 0;
  v_existing_source_sweep numeric(78,0) := 0;
  v_existing_boost_release numeric(78,0) := 0;
begin
  perform pg_advisory_xact_lock(
    hashtextextended(
      'veinvite_reward_reservation_' || new.network,
      0
    )
  );
  perform pg_advisory_xact_lock(
    hashtextextended(
      'veinvite_reward_boost_reserve_' ||
      new.network || '_' || new.app_id,
      0
    )
  );

  if new.entry_kind = 'SOURCE_SWEEP' then
    select * into v_source_receipt
    from public.vebetter_round_allocations a
    where a.id = new.source_allocation_receipt_id;

    if not found
       or v_source_receipt.network <> new.network
       or v_source_receipt.app_id <> new.app_id
       or v_source_receipt.vebetter_round_id + 1 <>
          new.source_reward_cohort_round_id then
      raise exception 'REWARD_BOOST_RESERVE_SOURCE_MISMATCH';
    end if;

    select * into v_protection
    from public.reward_boost_reserve_source_protections p
    where p.network=new.network
      and p.app_id=new.app_id
      and p.source_reward_cohort_round_id=
          new.source_reward_cohort_round_id
      and p.source_allocation_receipt_id=
          new.source_allocation_receipt_id;

    if not found then
      raise exception 'REWARD_BOOST_RESERVE_SOURCE_PROTECTION_REQUIRED';
    end if;

    select coalesce(sum(l.amount_wei),0)
    into v_existing_source_sweep
    from public.reward_boost_reserve_ledger l
    where l.network=new.network
      and l.app_id=new.app_id
      and l.entry_kind='SOURCE_SWEEP'
      and l.source_reward_cohort_round_id=
          new.source_reward_cohort_round_id
      and l.source_allocation_receipt_id=
          new.source_allocation_receipt_id;

    if v_existing_source_sweep + new.amount_wei >
       v_protection.max_sweepable_wei then
      raise exception 'REWARD_BOOST_RESERVE_SOURCE_PROTECTION_EXCEEDED';
    end if;

    v_budget := public.read_reward_cohort_effective_budget_wei(
      new.network,new.app_id,
      new.source_reward_cohort_round_id,
      new.source_allocation_receipt_id
    );

    v_committed := public.read_reward_cohort_committed_wei(
      new.network,new.app_id,
      new.source_reward_cohort_round_id,
      new.source_allocation_receipt_id
    );

    if new.amount_wei > greatest(v_budget-v_committed,0) then
      raise exception 'REWARD_BOOST_RESERVE_SOURCE_EXCEEDED';
    end if;
  else
    select * into v_destination_receipt
    from public.vebetter_round_allocations a
    where a.id = new.destination_allocation_receipt_id;

    if not found
       or v_destination_receipt.network <> new.network
       or v_destination_receipt.app_id <> new.app_id
       or v_destination_receipt.vebetter_round_id + 1 <>
          new.destination_reward_cohort_round_id then
      raise exception 'REWARD_BOOST_RESERVE_DESTINATION_MISMATCH';
    end if;

    v_balance := public.read_reward_boost_reserve_balance_wei(
      new.network,new.app_id
    );

    if new.entry_kind='BOOST_RELEASE' then
      select * into v_destination_plan
      from public.reward_boost_reserve_destination_plans d
      where d.network=new.network
        and d.app_id=new.app_id
        and d.destination_reward_cohort_round_id=
            new.destination_reward_cohort_round_id
        and d.destination_allocation_receipt_id=
            new.destination_allocation_receipt_id;

      if not found then
        raise exception 'REWARD_BOOST_DESTINATION_PLAN_REQUIRED';
      end if;

      select coalesce(sum(l.amount_wei),0)
      into v_existing_boost_release
      from public.reward_boost_reserve_ledger l
      where l.network=new.network
        and l.app_id=new.app_id
        and l.entry_kind='BOOST_RELEASE'
        and l.destination_reward_cohort_round_id=
            new.destination_reward_cohort_round_id
        and l.destination_allocation_receipt_id=
            new.destination_allocation_receipt_id;

      if v_existing_boost_release + new.amount_wei >
         v_destination_plan.max_boost_release_wei then
        raise exception 'REWARD_BOOST_DESTINATION_PLAN_EXCEEDED';
      end if;

      v_stress_reserve :=
        public.read_reward_boost_reserve_bank_stress_reserve_wei(
          new.network,new.app_id
        );
      v_releaseable:=greatest(v_balance-v_stress_reserve,0);

      if new.amount_wei > v_releaseable then
        raise exception 'REWARD_BOOST_RESERVE_STRESS_RESERVE_PROTECTED';
      end if;
    elsif new.amount_wei > v_balance then
      raise exception 'REWARD_BOOST_RESERVE_BALANCE_EXCEEDED';
    end if;
  end if;

  return new;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.seal_and_sweep_reward_boost_reserve_source(p_network text, p_app_id text, p_source_reward_cohort_round_id bigint, p_source_allocation_receipt_id bigint, p_policy_version text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
declare
  v_cfg public.reward_runtime_config%rowtype;
  v_existing public.reward_boost_reserve_source_protections%rowtype;
  v_existing_ledger_id bigint;
  v_candidate jsonb;
  v_revision_before text;
  v_revision_after text;
  v_protection public.reward_boost_reserve_source_protections%rowtype;
  v_ledger public.reward_boost_reserve_ledger%rowtype;
  v_amount numeric(78,0);
  v_reference_key text;
begin
  p_network:=lower(btrim(p_network));
  p_app_id:=lower(btrim(p_app_id));
  p_policy_version:=btrim(p_policy_version);

  perform pg_advisory_xact_lock(
    hashtextextended(
      'veinvite_reward_reservation_' || p_network,0
    )
  );
  perform pg_advisory_xact_lock(
    hashtextextended(
      'veinvite_reward_boost_reserve_' ||
      p_network || '_' || p_app_id,0
    )
  );

  select * into v_cfg
  from public.reward_runtime_config
  where id=1
  for update;

  if not found then
    raise exception 'REWARD_RUNTIME_CONFIG_MISSING';
  end if;
  if not v_cfg.reward_boost_reserve_enabled then
    raise exception 'REWARD_BOOST_RESERVE_DISABLED';
  end if;
  if v_cfg.emergency_rewards_paused then
    raise exception 'REWARD_BOOST_RESERVE_PAUSED';
  end if;
  if p_network='mainnet'
     and not v_cfg.mainnet_funded_rewards_enabled then
    raise exception 'REWARD_BOOST_RESERVE_MAINNET_DISABLED';
  end if;

  select * into v_existing
  from public.reward_boost_reserve_source_protections p
  where p.network=p_network
    and p.app_id=p_app_id
    and p.source_reward_cohort_round_id=
        p_source_reward_cohort_round_id
    and p.source_allocation_receipt_id=
        p_source_allocation_receipt_id;

  if found then
    select l.id
    into v_existing_ledger_id
    from public.reward_boost_reserve_ledger l
    where l.network=p_network
      and l.app_id=p_app_id
      and l.entry_kind='SOURCE_SWEEP'
      and l.source_reward_cohort_round_id=
          p_source_reward_cohort_round_id
      and l.source_allocation_receipt_id=
          p_source_allocation_receipt_id
      and (l.details->>'protectionId')::bigint=v_existing.id
    order by l.id
    limit 1;

    return jsonb_build_object(
      'changed',false,
      'protectionId',v_existing.id,
      'sourceSweepLedgerId',v_existing_ledger_id,
      'maxSweepableWei',
        v_existing.max_sweepable_wei::text,
      'sourceRevision',v_existing.source_revision
    );
  end if;

  perform 1
  from public.invitations i
  where i.activation_network=p_network
    and i.reward_cohort_round_id=
      p_source_reward_cohort_round_id
    and i.reward_funding_allocation_receipt_id=
      p_source_allocation_receipt_id
  for update;

  v_revision_before:=
    public.read_reward_boost_reserve_source_revision(
      p_network,p_app_id
    );

  v_candidate:=
    public.read_reward_boost_reserve_source_candidate(
      p_network,p_app_id,
      p_source_reward_cohort_round_id,
      p_source_allocation_receipt_id
    );

  v_revision_after:=
    public.read_reward_boost_reserve_source_revision(
      p_network,p_app_id
    );

  if v_revision_before<>v_revision_after
     or v_candidate->>'sourceRevision'<>v_revision_after then
    raise exception 'REWARD_BOOST_RESERVE_RECALCULATE';
  end if;

  insert into public.reward_boost_reserve_source_protections(
    network,app_id,
    source_reward_cohort_round_id,
    source_allocation_receipt_id,
    baseline_effective_budget_wei,
    baseline_committed_wei,
    promotion_original_wei,
    promotion_reserve_wei,
    late_reward_wei,
    queued_eligible_count,
    long_incomplete_count,
    late_weighted_bps,
    late_weighted_liability_wei,
    max_sweepable_wei,
    source_revision,
    policy_version
  ) values (
    p_network,p_app_id,
    p_source_reward_cohort_round_id,
    p_source_allocation_receipt_id,
    (v_candidate->>'baselineEffectiveBudgetWei')::numeric,
    (v_candidate->>'baselineCommittedWei')::numeric,
    (v_candidate->>'promotionOriginalWei')::numeric,
    (v_candidate->>'promotionReserveWei')::numeric,
    (v_candidate->>'lateRewardWei')::numeric,
    (v_candidate->>'queuedEligibleCount')::integer,
    (v_candidate->>'longIncompleteCount')::integer,
    (v_candidate->>'lateWeightedBps')::numeric,
    (v_candidate->>'lateWeightedLiabilityWei')::numeric,
    (v_candidate->>'maxSweepableWei')::numeric,
    v_revision_after,
    p_policy_version
  )
  returning * into v_protection;

  v_amount:=v_protection.max_sweepable_wei;

  if v_amount>0 then
    v_reference_key:=
      'source-protection:' ||
      p_source_allocation_receipt_id::text || ':' ||
      v_protection.source_revision;

    insert into public.reward_boost_reserve_ledger(
      network,app_id,entry_kind,
      source_reward_cohort_round_id,
      source_allocation_receipt_id,
      amount_wei,policy_version,reference_key,details
    ) values (
      p_network,p_app_id,'SOURCE_SWEEP',
      p_source_reward_cohort_round_id,
      p_source_allocation_receipt_id,
      v_amount,p_policy_version,v_reference_key,
      jsonb_build_object(
        'protectionId',v_protection.id,
        'sourceRevision',v_protection.source_revision,
        'promotionReserveWei',
          v_protection.promotion_reserve_wei::text,
        'lateWeightedLiabilityWei',
          v_protection.late_weighted_liability_wei::text
      )
    )
    returning * into v_ledger;
  end if;

  return jsonb_build_object(
    'changed',true,
    'protectionId',v_protection.id,
    'sourceSweepLedgerId',
      case when v_amount>0 then v_ledger.id else null end,
    'maxSweepableWei',v_amount::text,
    'promotionReserveWei',
      v_protection.promotion_reserve_wei::text,
    'lateRewardWei',v_protection.late_reward_wei::text,
    'lateWeightedLiabilityWei',
      v_protection.late_weighted_liability_wei::text,
    'sourceRevision',v_protection.source_revision
  );
end;
$function$
;

CREATE OR REPLACE FUNCTION public.seal_and_release_reward_boost_destination(p_network text, p_app_id text, p_observed_pool_balance_wei numeric, p_policy_version text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
declare
  v_cfg public.reward_runtime_config%rowtype;
  v_receipt public.vebetter_round_allocations%rowtype;
  v_existing public.reward_boost_reserve_destination_plans%rowtype;
  v_existing_ledger_id bigint;
  v_plan public.reward_boost_reserve_destination_plans%rowtype;
  v_ledger public.reward_boost_reserve_ledger%rowtype;
  v_current_round bigint;
  v_planning jsonb;
  v_funding_adjustment numeric(78,0);
  v_fresh_designated numeric(78,0);
  v_committed numeric(78,0);
  v_fresh_available numeric(78,0);
  v_reserved_existing numeric(78,0);
  v_physical_unreserved numeric(78,0);
  v_bank_balance numeric(78,0);
  v_bank_stress numeric(78,0);
  v_bank_available numeric(78,0);
  v_recent_protected numeric(78,0);
  v_source_retained numeric(78,0);
  v_current_pricing numeric(78,0);
  v_physical_headroom numeric(78,0);
  v_max_release numeric(78,0);
  v_reference_key text;
begin
  p_network:=lower(btrim(p_network));
  p_app_id:=lower(btrim(p_app_id));
  p_policy_version:=btrim(p_policy_version);

  if p_observed_pool_balance_wei is null
     or p_observed_pool_balance_wei<0
     or p_observed_pool_balance_wei<>
        trunc(p_observed_pool_balance_wei) then
    raise exception 'INVALID_REWARD_BOOST_OBSERVED_POOL';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended(
      'veinvite_reward_reservation_' || p_network,0
    )
  );
  perform pg_advisory_xact_lock(
    hashtextextended(
      'veinvite_reward_boost_reserve_' ||
      p_network || '_' || p_app_id,0
    )
  );

  select * into v_cfg
  from public.reward_runtime_config
  where id=1
  for update;

  if not found then
    raise exception 'REWARD_RUNTIME_CONFIG_MISSING';
  end if;
  if not v_cfg.reward_boost_reserve_enabled then
    raise exception 'REWARD_BOOST_RESERVE_DISABLED';
  end if;
  if v_cfg.emergency_rewards_paused then
    raise exception 'REWARD_BOOST_RESERVE_PAUSED';
  end if;
  if p_network='mainnet'
     and not v_cfg.mainnet_funded_rewards_enabled then
    raise exception 'REWARD_BOOST_RESERVE_MAINNET_DISABLED';
  end if;

  select * into v_receipt
  from public.vebetter_round_allocations a
  where a.network=p_network
    and a.app_id=p_app_id
  order by a.vebetter_round_id desc,a.id desc
  limit 1;

  if not found then
    return jsonb_build_object(
      'changed',false,
      'reason','ALLOCATION_UNAVAILABLE'
    );
  end if;

  v_current_round:=v_receipt.vebetter_round_id+1;

  select * into v_existing
  from public.reward_boost_reserve_destination_plans d
  where d.network=p_network
    and d.app_id=p_app_id
    and d.destination_reward_cohort_round_id=v_current_round
    and d.destination_allocation_receipt_id=v_receipt.id;

  if found then
    select l.id
    into v_existing_ledger_id
    from public.reward_boost_reserve_ledger l
    where l.network=p_network
      and l.app_id=p_app_id
      and l.entry_kind='BOOST_RELEASE'
      and l.destination_reward_cohort_round_id=v_current_round
      and l.destination_allocation_receipt_id=v_receipt.id
      and (l.details->>'destinationPlanId')::bigint=
          v_existing.id
    order by l.id
    limit 1;

    return jsonb_build_object(
      'changed',false,
      'planId',v_existing.id,
      'boostReleaseLedgerId',v_existing_ledger_id,
      'maxBoostReleaseWei',
        v_existing.max_boost_release_wei::text
    );
  end if;

  if exists (
    select 1
    from public.reward_boost_reserve_ledger l
    where l.network=p_network
      and l.app_id=p_app_id
      and l.entry_kind='BOOST_RELEASE'
      and l.destination_reward_cohort_round_id=v_current_round
      and l.destination_allocation_receipt_id=v_receipt.id
  ) then
    raise exception 'REWARD_BOOST_DESTINATION_UNPLANNED_RELEASE_EXISTS';
  end if;

  select coalesce(sum(a.amount_wei),0)
  into v_funding_adjustment
  from public.reward_cohort_funding_adjustments a
  where a.network=p_network
    and a.app_id=p_app_id
    and a.reward_cohort_round_id=v_current_round
    and a.allocation_receipt_id=v_receipt.id;

  v_fresh_designated:=
    v_receipt.rewards_allocation_amount_wei +
    v_funding_adjustment;

  v_committed:=
    public.read_reward_cohort_committed_wei(
      p_network,p_app_id,v_current_round,v_receipt.id
    );

  v_fresh_available:=greatest(
    v_fresh_designated-v_committed,
    0
  );

  v_planning:=public.read_reward_cohort_planning_snapshot(
    p_network,
    p_app_id,
    v_current_round,
    v_receipt.id
  );

  v_reserved_existing:=
    coalesce(
      nullif(v_planning->>'reservedExistingWei','')::numeric,
      0
    );

  v_physical_unreserved:=greatest(
    p_observed_pool_balance_wei-v_reserved_existing,
    0
  );

  v_bank_balance:=
    public.read_reward_boost_reserve_balance_wei(
      p_network,p_app_id
    );
  v_bank_stress:=
    public.read_reward_boost_reserve_bank_stress_reserve_wei(
      p_network,p_app_id
    );
  v_bank_available:=greatest(
    v_bank_balance-v_bank_stress,
    0
  );

  v_recent_protected:=
    public.read_reward_boost_reserve_recent_protected_wei(
      p_network,p_app_id,v_current_round
    );

  v_source_retained:=
    public.read_reward_boost_reserve_source_retained_wei(
      p_network,p_app_id
    );

  v_current_pricing:=least(
    v_fresh_available,
    v_physical_unreserved
  );

  v_physical_headroom:=greatest(
    v_physical_unreserved -
    v_current_pricing -
    v_recent_protected -
    v_source_retained -
    v_bank_stress,
    0
  );

  v_max_release:=least(
    v_current_pricing,
    v_bank_available,
    v_physical_headroom
  );

  if v_max_release<=0 then
    return jsonb_build_object(
      'changed',false,
      'reason','NO_SAFE_BOOST_CAPACITY',
      'currentRewardCohortRoundId',v_current_round,
      'bankBalanceWei',v_bank_balance::text,
      'bankStressReserveWei',v_bank_stress::text,
      'recentCohortProtectedWei',v_recent_protected::text,
      'sourceRetainedProtectionWei',v_source_retained::text,
      'physicalExtraHeadroomWei',v_physical_headroom::text
    );
  end if;

  insert into public.reward_boost_reserve_destination_plans(
    network,app_id,
    destination_reward_cohort_round_id,
    destination_allocation_receipt_id,
    baseline_fresh_designated_wei,
    baseline_committed_wei,
    baseline_fresh_pricing_capacity_wei,
    bank_balance_before_wei,
    bank_stress_reserve_wei,
    recent_cohort_protected_wei,
    source_retained_protection_wei,
    observed_pool_balance_wei,
    reserved_existing_wei,
    physical_extra_headroom_wei,
    max_boost_release_wei,
    policy_version
  ) values (
    p_network,p_app_id,
    v_current_round,v_receipt.id,
    v_fresh_designated,
    v_committed,
    v_current_pricing,
    v_bank_balance,
    v_bank_stress,
    v_recent_protected,
    v_source_retained,
    p_observed_pool_balance_wei,
    v_reserved_existing,
    v_physical_headroom,
    v_max_release,
    p_policy_version
  )
  returning * into v_plan;

  v_reference_key:=
    'boost-destination:' ||
    v_receipt.id::text || ':' ||
    v_plan.id::text;

  insert into public.reward_boost_reserve_ledger(
    network,app_id,entry_kind,
    destination_reward_cohort_round_id,
    destination_allocation_receipt_id,
    amount_wei,policy_version,reference_key,details
  ) values (
    p_network,p_app_id,'BOOST_RELEASE',
    v_current_round,v_receipt.id,
    v_max_release,p_policy_version,v_reference_key,
    jsonb_build_object(
      'destinationPlanId',v_plan.id,
      'bankStressReserveWei',v_bank_stress::text,
      'recentCohortProtectedWei',v_recent_protected::text,
      'sourceRetainedProtectionWei',v_source_retained::text,
      'physicalExtraHeadroomWei',v_physical_headroom::text
    )
  )
  returning * into v_ledger;

  return jsonb_build_object(
    'changed',true,
    'planId',v_plan.id,
    'boostReleaseLedgerId',v_ledger.id,
    'destinationRewardCohortRoundId',v_current_round,
    'destinationAllocationReceiptId',v_receipt.id,
    'maxBoostReleaseWei',v_max_release::text,
    'freshPricingCapacityWei',v_current_pricing::text,
    'bankBalanceWei',v_bank_balance::text,
    'bankStressReserveWei',v_bank_stress::text,
    'recentCohortProtectedWei',v_recent_protected::text,
    'sourceRetainedProtectionWei',v_source_retained::text,
    'physicalExtraHeadroomWei',v_physical_headroom::text
  );
end;
$function$
;

CREATE OR REPLACE FUNCTION public.append_reward_boost_reserve_release(p_network text, p_app_id text, p_entry_kind text, p_destination_reward_cohort_round_id bigint, p_destination_allocation_receipt_id bigint, p_amount_wei numeric, p_policy_version text, p_reference_key text, p_details jsonb DEFAULT '{}'::jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
declare
  v_cfg public.reward_runtime_config%rowtype;
  v_kind text := upper(btrim(p_entry_kind));
  v_existing public.reward_boost_reserve_ledger%rowtype;
  v_row public.reward_boost_reserve_ledger%rowtype;
begin
  p_network := lower(btrim(p_network));
  p_app_id := lower(btrim(p_app_id));
  p_policy_version := btrim(p_policy_version);
  p_reference_key := btrim(p_reference_key);

  if v_kind not in ('BOOST_RELEASE','LATE_COMPLETION_RELEASE') then
    raise exception 'INVALID_REWARD_BOOST_RESERVE_RELEASE_KIND';
  end if;
  if p_amount_wei is null
     or p_amount_wei <= 0
     or p_amount_wei <> trunc(p_amount_wei) then
    raise exception 'INVALID_REWARD_BOOST_RESERVE_AMOUNT';
  end if;
  if p_details is null or jsonb_typeof(p_details) <> 'object' then
    raise exception 'INVALID_REWARD_BOOST_RESERVE_DETAILS';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended('veinvite_reward_reservation_' || p_network,0)
  );
  perform pg_advisory_xact_lock(
    hashtextextended(
      'veinvite_reward_boost_reserve_' || p_network || '_' || p_app_id,
      0
    )
  );

  select * into v_existing
  from public.reward_boost_reserve_ledger l
  where l.network=p_network
    and l.app_id=p_app_id
    and l.reference_key=p_reference_key;

  if found then
    if v_existing.entry_kind<>v_kind
       or v_existing.destination_reward_cohort_round_id<>p_destination_reward_cohort_round_id
       or v_existing.destination_allocation_receipt_id<>p_destination_allocation_receipt_id
       or v_existing.amount_wei<>p_amount_wei
       or v_existing.policy_version<>p_policy_version then
      raise exception 'REWARD_BOOST_RESERVE_REFERENCE_KEY_CONFLICT';
    end if;

    return jsonb_build_object(
      'changed',false,
      'id',v_existing.id,
      'entryKind',v_existing.entry_kind,
      'amountWei',v_existing.amount_wei::text,
      'referenceKey',v_existing.reference_key,
      'createdAt',v_existing.created_at
    );
  end if;

  select * into v_cfg
  from public.reward_runtime_config
  where id=1
  for update;

  if not found then
    raise exception 'REWARD_RUNTIME_CONFIG_MISSING';
  end if;
  if not v_cfg.reward_boost_reserve_enabled then
    raise exception 'REWARD_BOOST_RESERVE_DISABLED';
  end if;
  if v_cfg.emergency_rewards_paused then
    raise exception 'REWARD_BOOST_RESERVE_PAUSED';
  end if;
  if p_network='mainnet' and not v_cfg.mainnet_funded_rewards_enabled then
    raise exception 'REWARD_BOOST_RESERVE_MAINNET_DISABLED';
  end if;

  insert into public.reward_boost_reserve_ledger(
    network,
    app_id,
    entry_kind,
    destination_reward_cohort_round_id,
    destination_allocation_receipt_id,
    amount_wei,
    policy_version,
    reference_key,
    details
  ) values (
    p_network,
    p_app_id,
    v_kind,
    p_destination_reward_cohort_round_id,
    p_destination_allocation_receipt_id,
    p_amount_wei,
    p_policy_version,
    p_reference_key,
    p_details
  )
  returning * into v_row;

  return jsonb_build_object(
    'changed',true,
    'id',v_row.id,
    'entryKind',v_row.entry_kind,
    'amountWei',v_row.amount_wei::text,
    'referenceKey',v_row.reference_key,
    'createdAt',v_row.created_at
  );
end;
$function$
;

