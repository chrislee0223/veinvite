CREATE OR REPLACE FUNCTION public.commit_reward_reservation_with_late_reserve(p_invite_code text, p_network text, p_observed_pool_balance_wei numeric, p_expected_reserved_before_wei numeric, p_amount_wei numeric, p_algorithm_version text, p_quote_snapshot_id bigint, p_finalized_block bigint, p_basis jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
declare
  v_code text := upper(btrim(p_invite_code));
  v_network text := lower(btrim(p_network));
  v_invitation public.invitations%rowtype;
  v_protection public.reward_boost_reserve_source_protections%rowtype;
  v_current_cohort bigint;
  v_long_rounds integer;
  v_reserve_enabled boolean;
  v_effective_budget numeric(78,0) := 0;
  v_committed numeric(78,0) := 0;
  v_required_release numeric(78,0) := 0;
  v_reference_key text;
  v_result jsonb;
  v_failure jsonb;
  v_message text;
  v_basis jsonb := coalesce(p_basis,'{}'::jsonb);
begin
  if v_network not in ('mainnet','testnet','testnet-staging') then
    raise exception 'UNSUPPORTED_NETWORK';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended('veinvite_reward_reservation_' || v_network,0)
  );

  select
    reward_boost_reserve_enabled,
    reward_boost_reserve_long_incomplete_rounds
  into
    v_reserve_enabled,
    v_long_rounds
  from public.reward_runtime_config
  where id=1;

  if not found then
    raise exception 'REWARD_RUNTIME_CONFIG_MISSING';
  end if;

  select * into v_invitation
  from public.invitations i
  where i.invite_code=v_code
    and i.activation_network=v_network
  for update;

  if not found
     or v_invitation.reward_cohort_round_id is null
     or v_invitation.reward_funding_allocation_receipt_id is null then
    return public.commit_reward_reservation(
      p_invite_code,p_network,p_observed_pool_balance_wei,
      p_expected_reserved_before_wei,p_amount_wei,
      p_algorithm_version,p_quote_snapshot_id,
      p_finalized_block,p_basis
    );
  end if;

  select max(a.vebetter_round_id+1)
  into v_current_cohort
  from public.vebetter_round_allocations a
  where a.network=v_network
    and a.app_id=
      '0x29acc8863cf2ab7a82d16c62d61ca84b6650cede4c4fd69073148c875349021e';

  if v_current_cohort is null
     or v_invitation.reward_cohort_round_id >
        v_current_cohort-v_long_rounds then
    return public.commit_reward_reservation(
      p_invite_code,p_network,p_observed_pool_balance_wei,
      p_expected_reserved_before_wei,p_amount_wei,
      p_algorithm_version,p_quote_snapshot_id,
      p_finalized_block,p_basis
    );
  end if;

  select * into v_protection
  from public.reward_boost_reserve_source_protections p
  where p.network=v_network
    and p.app_id=
      '0x29acc8863cf2ab7a82d16c62d61ca84b6650cede4c4fd69073148c875349021e'
    and p.source_reward_cohort_round_id=
      v_invitation.reward_cohort_round_id
    and p.source_allocation_receipt_id=
      v_invitation.reward_funding_allocation_receipt_id;

  if not found or not v_reserve_enabled then
    return public.commit_reward_reservation(
      p_invite_code,p_network,p_observed_pool_balance_wei,
      p_expected_reserved_before_wei,p_amount_wei,
      p_algorithm_version,p_quote_snapshot_id,
      p_finalized_block,p_basis
    );
  end if;

  if p_amount_wei<>v_protection.late_reward_wei then
    return jsonb_build_object(
      'reserved',false,
      'reason','RECALCULATE',
      'expectedLateRewardWei',
        v_protection.late_reward_wei::text
    );
  end if;

  v_effective_budget :=
    public.read_reward_cohort_effective_budget_wei(
      v_network,
      '0x29acc8863cf2ab7a82d16c62d61ca84b6650cede4c4fd69073148c875349021e',
      v_invitation.reward_cohort_round_id,
      v_invitation.reward_funding_allocation_receipt_id
    );

  v_committed :=
    public.read_reward_cohort_committed_wei(
      v_network,
      '0x29acc8863cf2ab7a82d16c62d61ca84b6650cede4c4fd69073148c875349021e',
      v_invitation.reward_cohort_round_id,
      v_invitation.reward_funding_allocation_receipt_id
    );

  v_required_release :=
    greatest(
      v_committed +
      p_amount_wei +
      v_protection.promotion_reserve_wei -
      v_effective_budget,
      0
    );

  v_reference_key :=
    'late-completion:' || v_network || ':' || v_code;

  v_basis := v_basis || jsonb_build_object(
    'lateCompletion',true,
    'lateCompletionProtectionId',v_protection.id,
    'lateCompletionCurrentCohortRoundId',v_current_cohort,
    'lateCompletionOriginalCohortRoundId',
      v_invitation.reward_cohort_round_id,
    'lateCompletionProtectedRewardWei',
      v_protection.late_reward_wei::text,
    'lateCompletionReserveTopUpWei',
      v_required_release::text,
    'lateCompletionReserveReferenceKey',
      v_reference_key,
    'lateCompletionSourceRevision',
      v_protection.source_revision
  );

  begin
    if v_required_release>0 then
      perform public.append_reward_boost_reserve_release(
        v_network,
        '0x29acc8863cf2ab7a82d16c62d61ca84b6650cede4c4fd69073148c875349021e',
        'LATE_COMPLETION_RELEASE',
        v_invitation.reward_cohort_round_id,
        v_invitation.reward_funding_allocation_receipt_id,
        v_required_release,
        'late-completion-reserve-v1',
        v_reference_key,
        jsonb_build_object(
          'inviteCode',v_code,
          'protectionId',v_protection.id,
          'currentCohortRoundId',v_current_cohort,
          'originalCohortRoundId',
            v_invitation.reward_cohort_round_id
        )
      );
    end if;

    v_result := public.commit_reward_reservation(
      p_invite_code,p_network,p_observed_pool_balance_wei,
      p_expected_reserved_before_wei,p_amount_wei,
      p_algorithm_version,p_quote_snapshot_id,
      p_finalized_block,v_basis
    );

    if coalesce((v_result->>'reserved')::boolean,false) then
      return v_result || jsonb_build_object(
        'lateCompletion',true,
        'reserveTopUpWei',v_required_release::text,
        'protectedRewardWei',
          v_protection.late_reward_wei::text
      );
    end if;

    v_failure:=v_result;
    raise exception 'LATE_RESERVE_ROLLBACK';
  exception
    when raise_exception then
      get stacked diagnostics v_message=message_text;
      if v_message='LATE_RESERVE_ROLLBACK' then
        return v_failure;
      end if;
      raise;
  end;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.read_reward_boost_reserve_unprotected_sources(p_network text, p_app_id text)
 RETURNS TABLE(reward_cohort_round_id bigint, allocation_receipt_id bigint)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
declare
  v_long_rounds integer;
  v_current_cohort bigint;
begin
  p_network:=lower(btrim(p_network));
  p_app_id:=lower(btrim(p_app_id));

  select reward_boost_reserve_long_incomplete_rounds
  into v_long_rounds
  from public.reward_runtime_config
  where id=1;

  if not found then
    raise exception 'REWARD_RUNTIME_CONFIG_MISSING';
  end if;

  select max(a.vebetter_round_id+1)
  into v_current_cohort
  from public.vebetter_round_allocations a
  where a.network=p_network
    and a.app_id=p_app_id;

  if v_current_cohort is null then
    return;
  end if;

  return query
  select
    a.vebetter_round_id+1,
    a.id
  from public.vebetter_round_allocations a
  where a.network=p_network
    and a.app_id=p_app_id
    and a.vebetter_round_id+1 <=
      v_current_cohort-v_long_rounds
    and not exists (
      select 1
      from public.reward_boost_reserve_source_protections p
      where p.network=p_network
        and p.app_id=p_app_id
        and p.source_reward_cohort_round_id=
            a.vebetter_round_id+1
        and p.source_allocation_receipt_id=a.id
    )
  order by a.vebetter_round_id,a.id;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.read_reward_boost_reserve_audit_snapshot(p_network text, p_app_id text)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
declare
  v_enabled boolean;
  v_shadow_enabled boolean;
  v_current_cohort bigint;
  v_source_inflow numeric(78,0);
  v_boost_outflow numeric(78,0);
  v_late_outflow numeric(78,0);
  v_bank_balance numeric(78,0);
  v_bank_stress numeric(78,0);
  v_source_retained numeric(78,0);
  v_recent_protected numeric(78,0);
  v_source_protection_count integer;
  v_destination_plan_count integer;
  v_unprotected_count integer;
  v_source_overrun_count integer;
  v_destination_overrun_count integer;
begin
  p_network:=lower(btrim(p_network));
  p_app_id:=lower(btrim(p_app_id));

  select
    reward_boost_reserve_enabled,
    reward_boost_reserve_shadow_enabled
  into
    v_enabled,
    v_shadow_enabled
  from public.reward_runtime_config
  where id=1;

  if not found then
    raise exception 'REWARD_RUNTIME_CONFIG_MISSING';
  end if;

  select max(a.vebetter_round_id+1)
  into v_current_cohort
  from public.vebetter_round_allocations a
  where a.network=p_network
    and a.app_id=p_app_id;

  select
    coalesce(sum(l.amount_wei) filter (
      where l.entry_kind='SOURCE_SWEEP'
    ),0),
    coalesce(sum(l.amount_wei) filter (
      where l.entry_kind='BOOST_RELEASE'
    ),0),
    coalesce(sum(l.amount_wei) filter (
      where l.entry_kind='LATE_COMPLETION_RELEASE'
    ),0)
  into
    v_source_inflow,
    v_boost_outflow,
    v_late_outflow
  from public.reward_boost_reserve_ledger l
  where l.network=p_network
    and l.app_id=p_app_id;

  v_bank_balance :=
    v_source_inflow-v_boost_outflow-v_late_outflow;

  v_bank_stress :=
    public.read_reward_boost_reserve_bank_stress_reserve_wei(
      p_network,p_app_id
    );

  v_source_retained :=
    public.read_reward_boost_reserve_source_retained_wei(
      p_network,p_app_id
    );

  v_recent_protected :=
    case
      when v_current_cohort is null then 0
      else public.read_reward_boost_reserve_recent_protected_wei(
        p_network,p_app_id,v_current_cohort
      )
    end;

  select count(*)::integer
  into v_source_protection_count
  from public.reward_boost_reserve_source_protections p
  where p.network=p_network
    and p.app_id=p_app_id;

  select count(*)::integer
  into v_destination_plan_count
  from public.reward_boost_reserve_destination_plans d
  where d.network=p_network
    and d.app_id=p_app_id;

  select count(*)::integer
  into v_unprotected_count
  from public.read_reward_boost_reserve_unprotected_sources(
    p_network,p_app_id
  );

  select count(*)::integer
  into v_source_overrun_count
  from (
    select
      p.id,
      p.max_sweepable_wei,
      coalesce(sum(l.amount_wei),0) as swept_wei
    from public.reward_boost_reserve_source_protections p
    left join public.reward_boost_reserve_ledger l
      on l.network=p.network
     and l.app_id=p.app_id
     and l.entry_kind='SOURCE_SWEEP'
     and l.source_reward_cohort_round_id=
         p.source_reward_cohort_round_id
     and l.source_allocation_receipt_id=
         p.source_allocation_receipt_id
    where p.network=p_network
      and p.app_id=p_app_id
    group by p.id,p.max_sweepable_wei
    having coalesce(sum(l.amount_wei),0)>
           p.max_sweepable_wei
  ) x;

  select count(*)::integer
  into v_destination_overrun_count
  from (
    select
      d.id,
      d.max_boost_release_wei,
      coalesce(sum(l.amount_wei),0) as released_wei
    from public.reward_boost_reserve_destination_plans d
    left join public.reward_boost_reserve_ledger l
      on l.network=d.network
     and l.app_id=d.app_id
     and l.entry_kind='BOOST_RELEASE'
     and l.destination_reward_cohort_round_id=
         d.destination_reward_cohort_round_id
     and l.destination_allocation_receipt_id=
         d.destination_allocation_receipt_id
    where d.network=p_network
      and d.app_id=p_app_id
    group by d.id,d.max_boost_release_wei
    having coalesce(sum(l.amount_wei),0)>
           d.max_boost_release_wei
  ) x;

  return jsonb_build_object(
    'enabled',v_enabled,
    'shadowEnabled',v_shadow_enabled,
    'currentRewardCohortRoundId',v_current_cohort,
    'sourceInflowWei',v_source_inflow::text,
    'boostOutflowWei',v_boost_outflow::text,
    'lateCompletionOutflowWei',v_late_outflow::text,
    'bankBalanceWei',v_bank_balance::text,
    'bankStressReserveWei',v_bank_stress::text,
    'ordinaryBoostAvailableWei',
      greatest(v_bank_balance-v_bank_stress,0)::text,
    'sourceRetainedProtectionWei',v_source_retained::text,
    'recentCohortProtectedWei',v_recent_protected::text,
    'sourceProtectionCount',v_source_protection_count,
    'destinationPlanCount',v_destination_plan_count,
    'unprotectedMatureSourceCount',v_unprotected_count,
    'sourceOverrunCount',v_source_overrun_count,
    'destinationOverrunCount',v_destination_overrun_count,
    'conservationOk',
      v_bank_balance=
        v_source_inflow-v_boost_outflow-v_late_outflow,
    'stressReserveCovered',
      v_bank_balance>=v_bank_stress
  );
end;
