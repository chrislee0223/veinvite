CREATE OR REPLACE FUNCTION public.read_reward_boost_reserve_recent_protected_wei(p_network text, p_app_id text, p_current_reward_cohort_round_id bigint)
 RETURNS numeric
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
declare
  v_long_rounds integer;
  v_total numeric(78,0);
begin
  p_network:=lower(btrim(p_network));
  p_app_id:=lower(btrim(p_app_id));

  select reward_boost_reserve_long_incomplete_rounds
  into v_long_rounds
  from public.reward_runtime_config
  where id=1;

  if not found then
    raise exception 'REWARD_RUNTIME_CONFIG_MISSING';
  end if;

  select coalesce(sum(
    greatest(
      public.read_reward_cohort_effective_budget_wei(
        a.network,
        a.app_id,
        a.vebetter_round_id+1,
        a.id
      ) -
      public.read_reward_cohort_committed_wei(
        a.network,
        a.app_id,
        a.vebetter_round_id+1,
        a.id
      ),
      0
    )
  ),0)
  into v_total
  from public.vebetter_round_allocations a
  where a.network=p_network
    and a.app_id=p_app_id
    and a.vebetter_round_id+1 <
      p_current_reward_cohort_round_id
    and a.vebetter_round_id+1 >
      p_current_reward_cohort_round_id-v_long_rounds;

  return v_total;
end;
