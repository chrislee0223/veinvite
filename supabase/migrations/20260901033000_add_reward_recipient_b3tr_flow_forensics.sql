create table if not exists public.reward_recipient_b3tr_flow_snapshots (
  id bigint generated by default as identity primary key,
  receipt_id bigint not null references public.reward_receipts(id) on delete restrict,
  settlement_id bigint not null references public.reward_payout_transaction_settlements(id) on delete restrict,
  network text not null check (network in ('mainnet', 'testnet', 'testnet-staging')),
  recipient_wallet text not null check (recipient_wallet ~ '^0x[0-9a-f]{40}$'),
  payout_tx_id text not null check (payout_tx_id ~ '^0x[0-9a-f]{64}$'),
  payout_block_number bigint not null check (payout_block_number >= 0),
  payout_amount_wei numeric(78, 0) not null check (payout_amount_wei > 0),
  scan_to_block bigint not null check (scan_to_block >= payout_block_number),
  first_outbound_block bigint check (first_outbound_block is null or first_outbound_block > payout_block_number),
  first_outbound_tx_id text check (first_outbound_tx_id is null or first_outbound_tx_id ~ '^0x[0-9a-f]{64}$'),
  first_outbound_destination text check (first_outbound_destination is null or first_outbound_destination ~ '^0x[0-9a-f]{40}$'),
  first_outbound_amount_wei numeric(78, 0) check (first_outbound_amount_wei is null or first_outbound_amount_wei >= 0),
  first_outbound_blocks_after_payout bigint check (first_outbound_blocks_after_payout is null or first_outbound_blocks_after_payout > 0),
  dominant_destination text check (dominant_destination is null or dominant_destination ~ '^0x[0-9a-f]{40}$'),
  dominant_destination_amount_wei numeric(78, 0) not null default 0 check (dominant_destination_amount_wei >= 0),
  outbound_transfer_count integer not null default 0 check (outbound_transfer_count >= 0),
  distinct_destination_count integer not null default 0 check (distinct_destination_count >= 0),
  total_outbound_amount_wei numeric(78, 0) not null default 0 check (total_outbound_amount_wei >= 0),
  shared_destination_recipient_count integer not null default 0 check (shared_destination_recipient_count >= 0),
  known_protocol_destination boolean not null default false,
  indicators jsonb not null default '[]'::jsonb check (jsonb_typeof(indicators) = 'array'),
  observation_only boolean not null default true check (observation_only = true),
  checked_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  constraint reward_recipient_b3tr_flow_snapshot_shape check (
    (
      outbound_transfer_count = 0
      and first_outbound_block is null
      and first_outbound_tx_id is null
      and first_outbound_destination is null
      and first_outbound_amount_wei is null
      and first_outbound_blocks_after_payout is null
      and dominant_destination is null
      and dominant_destination_amount_wei = 0
      and distinct_destination_count = 0
      and total_outbound_amount_wei = 0
    )
    or
    (
      outbound_transfer_count > 0
      and first_outbound_block is not null
      and first_outbound_tx_id is not null
      and first_outbound_destination is not null
      and first_outbound_amount_wei is not null
      and first_outbound_blocks_after_payout is not null
      and dominant_destination is not null
      and dominant_destination_amount_wei > 0
      and distinct_destination_count > 0
      and total_outbound_amount_wei > 0
    )
  ),
  unique (receipt_id, scan_to_block)
);

create index if not exists reward_recipient_b3tr_flow_recipient_idx
  on public.reward_recipient_b3tr_flow_snapshots (network, recipient_wallet, checked_at desc);

create index if not exists reward_recipient_b3tr_flow_destination_idx
  on public.reward_recipient_b3tr_flow_snapshots (network, dominant_destination, checked_at desc)
  where dominant_destination is not null;

create index if not exists reward_recipient_b3tr_flow_receipt_idx
  on public.reward_recipient_b3tr_flow_snapshots (receipt_id, checked_at desc);

alter table public.reward_recipient_b3tr_flow_snapshots enable row level security;

revoke all on table public.reward_recipient_b3tr_flow_snapshots from public, anon, authenticated;
grant select, insert on table public.reward_recipient_b3tr_flow_snapshots to service_role;

do $$
begin
  if to_regclass('public.reward_recipient_b3tr_flow_snapshots_id_seq') is not null then
    execute 'grant usage, select on sequence public.reward_recipient_b3tr_flow_snapshots_id_seq to service_role';
  end if;
end;
$$;

create or replace function public.prevent_reward_recipient_b3tr_flow_snapshot_mutation()
returns trigger
language plpgsql
set search_path to 'public'
as $$
begin
  raise exception 'reward recipient B3TR flow snapshots are append-only';
end;
$$;

revoke all on function public.prevent_reward_recipient_b3tr_flow_snapshot_mutation() from public, anon, authenticated;

drop trigger if exists reward_recipient_b3tr_flow_snapshots_immutable
  on public.reward_recipient_b3tr_flow_snapshots;

create trigger reward_recipient_b3tr_flow_snapshots_immutable
before update or delete on public.reward_recipient_b3tr_flow_snapshots
for each row
execute function public.prevent_reward_recipient_b3tr_flow_snapshot_mutation();

create or replace view public.operator_reward_recipient_b3tr_forensics
with (security_invoker = true)
as
select
  l.receipt_id,
  l.network,
  l.vebetter_round_id,
  l.invite_code,
  l.recipient_wallet,
  l.amount_wei as payout_amount_wei,
  l.tx_id as payout_tx_id,
  l.paid_at,
  s.checked_at as latest_flow_checked_at,
  s.scan_to_block,
  s.first_outbound_block,
  s.first_outbound_tx_id,
  s.first_outbound_destination,
  s.first_outbound_amount_wei,
  s.first_outbound_blocks_after_payout,
  s.dominant_destination,
  s.dominant_destination_amount_wei,
  s.outbound_transfer_count,
  s.distinct_destination_count,
  s.total_outbound_amount_wei,
  s.shared_destination_recipient_count,
  s.known_protocol_destination,
  s.indicators,
  (s.id is not null) as has_b3tr_flow_scan
from public.reward_recipient_audit_ledger l
left join lateral (
  select x.*
  from public.reward_recipient_b3tr_flow_snapshots x
  where x.receipt_id = l.receipt_id
  order by x.checked_at desc, x.id desc
  limit 1
) s on true;

revoke all on table public.operator_reward_recipient_b3tr_forensics from public, anon, authenticated;
grant select on table public.operator_reward_recipient_b3tr_forensics to service_role;

