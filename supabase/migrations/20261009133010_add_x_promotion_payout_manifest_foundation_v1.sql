create or replace function public.create_reward_x_promotion_payout_manifest_v1(
  p_intent_id bigint,
  p_app_id text,
  p_x2earn_rewards_pool_address text,
  p_operator_wallet text,
  p_manifest_hash text,
  p_proof_text text,
  p_proof_link text,
  p_description text,
  p_clause jsonb
)
returns jsonb
language plpgsql
security definer
set search_path to 'pg_catalog','public'
as $function$
declare
  v_intent public.reward_x_promotion_payout_intents%rowtype;
  v_existing public.reward_x_promotion_payout_manifests%rowtype;
  v_manifest public.reward_x_promotion_payout_manifests%rowtype;
begin
  if p_intent_id is null or p_intent_id<1 then
    raise exception 'REWARD_X_PROMOTION_PAYOUT_MANIFEST_INTENT_INVALID';
  end if;

  p_app_id:=lower(btrim(coalesce(p_app_id,'')));
  p_x2earn_rewards_pool_address:=
    lower(btrim(coalesce(p_x2earn_rewards_pool_address,'')));
  p_operator_wallet:=lower(btrim(coalesce(p_operator_wallet,'')));
  p_manifest_hash:=lower(btrim(coalesce(p_manifest_hash,'')));
  p_proof_text:=btrim(coalesce(p_proof_text,''));
  p_proof_link:=btrim(coalesce(p_proof_link,''));
  p_description:=btrim(coalesce(p_description,''));

  select * into v_intent
  from public.reward_x_promotion_payout_intents i
  where i.id=p_intent_id;

  if not found then
    raise exception 'REWARD_X_PROMOTION_PAYOUT_INTENT_MISSING';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended('veinvite_x_promotion_' || v_intent.invite_code,0)
  );

  select * into v_existing
  from public.reward_x_promotion_payout_manifests m
  where m.intent_id=p_intent_id;

  if found then
    if v_existing.app_id=p_app_id
       and v_existing.x2earn_rewards_pool_address=p_x2earn_rewards_pool_address
       and v_existing.operator_wallet=p_operator_wallet
       and v_existing.manifest_hash=p_manifest_hash
       and v_existing.proof_text=p_proof_text
       and v_existing.proof_link=p_proof_link
       and v_existing.description=p_description
       and v_existing.clause=p_clause then
      return jsonb_build_object(
        'created',false,
        'manifestId',v_existing.id,
        'intentId',v_existing.intent_id,
        'manifestHash',v_existing.manifest_hash
      );
    end if;

    raise exception 'REWARD_X_PROMOTION_PAYOUT_MANIFEST_IMMUTABLE_MISMATCH';
  end if;

  insert into public.reward_x_promotion_payout_manifests(
    intent_id,
    network,
    app_id,
    x2earn_rewards_pool_address,
    operator_wallet,
    manifest_hash,
    invite_code,
    recipient_wallet,
    amount_wei,
    public_proof_id,
    proof_text,
    proof_link,
    description,
    clause
  ) values (
    v_intent.id,
    v_intent.network,
    p_app_id,
    p_x2earn_rewards_pool_address,
    p_operator_wallet,
    p_manifest_hash,
    v_intent.invite_code,
    v_intent.recipient_wallet,
    v_intent.amount_wei,
    v_intent.public_proof_id,
    p_proof_text,
    p_proof_link,
    p_description,
    p_clause
  )
  returning * into v_manifest;

  return jsonb_build_object(
    'created',true,
    'manifestId',v_manifest.id,
    'intentId',v_manifest.intent_id,
    'manifestHash',v_manifest.manifest_hash
  );
end;
$function$;

