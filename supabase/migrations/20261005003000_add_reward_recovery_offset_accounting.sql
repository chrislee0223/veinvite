create or replace function public.sync_reward_recovery_invalidation()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_obligation public.reward_recovery_obligations%rowtype;
  v_consumed numeric(78,0) := 0;
  v_settlement public.reward_recovery_settlements%rowtype;
begin
  if new.status = 'ACTIVE' then
    insert into public.reward_recovery_obligations(
      network,recipient_wallet,source_invalidation_id,source_receipt_id,
      source_invite_code,amount_wei,status,status_reason
    )
    select
      lower(r.network),lower(r.recipient_wallet),new.id,r.id,r.invite_code,
      r.amount_wei,'ACTIVE','ACTIVE_REFERRAL_INVALIDATION'
    from public.reward_receipts r
    where r.invite_code = new.invite_code
      and lower(r.network) = lower(new.network)
      and r.amount_wei > 0
    on conflict (network,source_invalidation_id,source_receipt_id)
    do update set
      status='ACTIVE',
      status_reason='REFERRAL_REINVALIDATED',
      updated_at=clock_timestamp();

    update public.reward_recovery_settlements s
    set
      state='INVALIDATED',
      updated_at=clock_timestamp()
    where s.network=lower(new.network)
      and s.invite_code=new.invite_code
      and s.state='ACTIVE';

    return new;
  end if;

  if new.status = 'REINSTATED' then
    for v_obligation in
      select *
      from public.reward_recovery_obligations o
      where o.source_invalidation_id = new.id
      for update
    loop
      select coalesce(sum(a.amount_wei),0)
      into v_consumed
      from public.reward_recovery_allocations a
      join public.reward_recovery_settlements s
        on s.id=a.settlement_id
       and s.state='ACTIVE'
      where a.obligation_id=v_obligation.id;

      if v_consumed > 0 then
        update public.reward_recovery_obligations
        set
          status='FROZEN',
          status_reason='SOURCE_INVALIDATION_REINSTATED_AFTER_CONSUMPTION',
          updated_at=clock_timestamp()
        where id=v_obligation.id;

        insert into public.reward_recovery_review_queue(
          network,recipient_wallet,invite_code,obligation_id,settlement_id,
          reason_kind,details
        ) values (
          v_obligation.network,
          v_obligation.recipient_wallet,
          v_obligation.source_invite_code,
          v_obligation.id,
          null,
          'SOURCE_INVALIDATION_REINSTATED_AFTER_CONSUMPTION',
          jsonb_build_object(
            'consumedWei',v_consumed::text,
            'obligationWei',v_obligation.amount_wei::text,
            'invalidationId',new.id::text
          )
        )
        on conflict (reason_kind,obligation_id,settlement_id) do nothing;
      else
        update public.reward_recovery_obligations
        set
          status='REVERSED',
          status_reason='SOURCE_INVALIDATION_REINSTATED_BEFORE_CONSUMPTION',
          updated_at=clock_timestamp()
        where id=v_obligation.id;
      end if;
    end loop;

    select *
    into v_settlement
    from public.reward_recovery_settlements s
    where s.network=lower(new.network)
      and s.invite_code=new.invite_code
      and s.state='INVALIDATED'
    for update;

    if found then
      update public.reward_recovery_settlements
      set state='REVIEW',updated_at=clock_timestamp()
      where id=v_settlement.id;

      insert into public.reward_recovery_review_queue(
        network,recipient_wallet,invite_code,obligation_id,settlement_id,
        reason_kind,details
      ) values (
        v_settlement.network,
        v_settlement.recipient_wallet,
        v_settlement.invite_code,
        null,
        v_settlement.id,
        'SETTLEMENT_INVALIDATION_REINSTATED',
        jsonb_build_object(
          'grossWei',v_settlement.gross_amount_wei::text,
          'offsetWei',v_settlement.offset_amount_wei::text,
          'netWei',v_settlement.net_amount_wei::text,
          'invalidationId',new.id::text
        )
      )
      on conflict (reason_kind,obligation_id,settlement_id) do nothing;
    end if;
  end if;

  return new;
end;
$$;

