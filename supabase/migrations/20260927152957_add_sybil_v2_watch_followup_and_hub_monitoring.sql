create or replace function public.enrich_operator_monitor_snapshot_sybil_v2_watch_followup()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_due bigint := 0;
  v_stale_due bigint := 0;
  v_flagged_24h bigint := 0;
  v_hubs bigint := 0;
  v_priority_hubs bigint := 0;
  v_extra_alerts jsonb := '[]'::jsonb;
begin
  if not public.sybil_v2_enforcement_enabled() then
    return new;
  end if;

  select count(*)::bigint
  into v_due
  from public.operator_sybil_v2_watch_followup_due d
  where d.network = new.network;

  select count(*)::bigint
  into v_stale_due
  from public.operator_sybil_v2_watch_followup_due d
  where d.network = new.network
    and d.due_at < clock_timestamp() - interval '2 hours';

  select count(*)::bigint
  into v_flagged_24h
  from public.operator_sybil_v2_watch_followup_flags f
  where f.network = new.network
    and f.checked_at >= clock_timestamp() - interval '24 hours';

  select count(*)::bigint,
         count(*) filter (where h.priority = 'PRIORITY')::bigint
  into v_hubs, v_priority_hubs
  from public.operator_sybil_v2_cluster_hub_candidates h
  where h.network = new.network;

  new.metrics := coalesce(new.metrics,'{}'::jsonb) ||
    jsonb_build_object(
      'sybilV2WatchFollowup',
      jsonb_build_object(
        'dueFollowups', v_due,
        'staleDueFollowups', v_stale_due,
        'flaggedFollowupsLast24h', v_flagged_24h,
        'clusterHubCandidates', v_hubs,
        'priorityClusterHubCandidates', v_priority_hubs,
        'followupHorizonsHours', jsonb_build_array(24,168,720),
        'automaticRestrictionFromHubOnly', false
      )
    );

  if v_stale_due > 0 then
    v_extra_alerts := v_extra_alerts || jsonb_build_array(
      jsonb_build_object(
        'code', 'SYBIL_V2_WATCH_FOLLOWUP_STALE',
        'severity', 'WARNING',
        'observed', v_stale_due,
        'message', 'One or more WATCH invitee follow-up scans are over two hours late.'
      )
    );
  end if;

  if v_flagged_24h > 0 then
    v_extra_alerts := v_extra_alerts || jsonb_build_array(
      jsonb_build_object(
        'code', 'SYBIL_V2_WATCH_FOLLOWUP_FLAGGED',
        'severity', 'WARNING',
        'observed', v_flagged_24h,
        'message', 'A WATCH invitee produced new same-subject B3TR flow evidence that deserves operator review. No automatic restriction was applied.'
      )
    );
  end if;

  new.alerts := coalesce(new.alerts,'[]'::jsonb) || v_extra_alerts;
  new.alert_count := jsonb_array_length(new.alerts);
  new.severity := case
    when new.alerts @> '[{"severity":"CRITICAL"}]'::jsonb then 'CRITICAL'
    when new.alert_count > 0 then 'WARNING'
    else 'NORMAL'
  end;

  return new;
end;
$$;

revoke all on function public.enrich_operator_monitor_snapshot_sybil_v2_watch_followup()
  from public, anon, authenticated, service_role;

drop trigger if exists ad_operator_monitor_sybil_v2_watch_followup_enrichment
