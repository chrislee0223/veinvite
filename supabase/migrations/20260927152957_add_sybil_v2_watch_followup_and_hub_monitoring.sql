create or replace view public.operator_sybil_v2_watch_followup_due
with (security_invoker = true)
as
select
  a.invite_code,
  a.network,
  lower(i.inviter_wallet) as inviter_wallet,
  lower(i.invitee_wallet) as subject_wallet,
  a.updated_at as watch_started_at,
  h.horizon_hours,
  a.updated_at + make_interval(hours => h.horizon_hours) as due_at,
  greatest(
    coalesce(
      last_observation.last_scan_to_block + 1,
      greatest(
        coalesce(
          a.evidence_cutoff_block,
          i.vote_completed_block,
          i.activation_block,
          0
        ) + 1,
        0
      )
    ),
    0
  )::bigint as scan_from_block
from public.sybil_v2_referral_assessments a
join public.invitations i
  on i.invite_code = a.invite_code
 and i.activation_network = a.network
left join lateral (
  select max(o.scan_to_block)::bigint as last_scan_to_block
  from public.sybil_v2_watch_followup_observations o
  where o.invite_code = a.invite_code
    and o.network = a.network
) last_observation on true
cross join lateral (
  select v.horizon_hours
  from (values (24),(168),(720)) as v(horizon_hours)
  where a.updated_at + make_interval(hours => v.horizon_hours) <= clock_timestamp()
    and not exists (
      select 1
      from public.sybil_v2_watch_followup_observations o
      where o.invite_code = a.invite_code
        and o.network = a.network
        and o.horizon_hours = v.horizon_hours
    )
  order by v.horizon_hours
  limit 1
) h
where public.sybil_v2_enforcement_enabled()
  and a.state = 'WATCH'
  and i.invitee_wallet is not null
  and i.inviter_wallet is not null;

revoke all on public.operator_sybil_v2_watch_followup_due
  from public, anon, authenticated;
grant select on public.operator_sybil_v2_watch_followup_due
  to service_role;

comment on view public.operator_sybil_v2_watch_followup_due is
  'Service-only scheduler for same-subject WATCH follow-up at 24h, 7d, and 30d. The subject is always the invitee wallet that received the WATCH verdict, never the inviter reward recipient.';

create or replace view public.operator_sybil_v2_cluster_hub_candidates
with (security_invoker = true)
as
with flows as (
  select
    h.network,
    h.invite_code,
    lower(h.wallet_address) as sender_wallet,
    lower(h.destination_wallet) as wallet_address,
    h.block_number,
    coalesce(h.block_timestamp, h.created_at) as observed_at
  from public.sybil_v2_preactivation_b3tr_outflows h

  union all

  select
    f.network,
    f.invite_code,
    lower(f.subject_wallet) as sender_wallet,
    lower(f.destination_wallet) as wallet_address,
    f.block_number,
    coalesce(f.block_timestamp, f.created_at) as observed_at
  from public.sybil_v2_watch_followup_outflows f
),
eligible_flows as (
  select distinct
    f.network,
    f.invite_code,
    f.sender_wallet,
    f.wallet_address,
    f.block_number,
    f.observed_at
  from flows f
  where f.sender_wallet <> f.wallet_address
    and not exists (
      select 1
      from public.sybil_v2_cluster_hub_allowlist a
      where a.network = f.network
        and a.wallet_address = f.wallet_address
    )
),
classified as (
  select
    f.*,
    exists (
      select 1
      from public.sybil_v2_wallet_restrictions r
      where r.network = f.network
        and r.wallet_address = f.sender_wallet
        and r.status = 'ACTIVE'
    ) as active_blacklisted_sender,
    exists (
      select 1
      from public.sybil_v2_referral_assessments a
      where a.invite_code = f.invite_code
        and a.network = f.network
        and a.state in ('WATCH','HOLD','RESTRICTED')
    ) as watched_sender,
    exists (
      select 1
      from public.invitations i
      where i.invite_code = f.invite_code
        and i.status = 'COMPLETED'
    ) as completed_sender
  from eligible_flows f
),
aggregated as (
  select
    network,
    wallet_address,
    count(distinct sender_wallet)::bigint as sender_count,
    count(distinct sender_wallet) filter (
      where active_blacklisted_sender
    )::bigint as active_blacklisted_sender_count,
    count(distinct sender_wallet) filter (
      where watched_sender
    )::bigint as watched_sender_count,
    count(distinct sender_wallet) filter (
      where completed_sender
    )::bigint as completed_sender_count,
    count(distinct invite_code)::bigint as invite_count,
    min(observed_at) as first_seen_at,
    max(observed_at) as last_seen_at
  from classified
  group by network, wallet_address
)
select
  a.network,
  a.wallet_address,
  'WATCH'::text as state,
  case
    when a.active_blacklisted_sender_count >= 3
      or a.sender_count >= 20 then 'PRIORITY'
    when a.active_blacklisted_sender_count >= 1
      or a.watched_sender_count >= 3
      or a.sender_count >= 10 then 'HIGH'
    else 'WATCH'
  end::text as priority,
  a.sender_count,
  a.active_blacklisted_sender_count,
  a.watched_sender_count,
  a.completed_sender_count,
  a.invite_count,
  a.first_seen_at,
  a.last_seen_at,
  jsonb_build_object(
    'senderCount', a.sender_count,
    'activeBlacklistedSenderCount', a.active_blacklisted_sender_count,
    'watchedSenderCount', a.watched_sender_count,
    'completedSenderCount', a.completed_sender_count,
    'inviteCount', a.invite_count,
    'automaticRestriction', false,
    'operatorReviewRequiredBeforeAllowlistOrRestriction', true
  ) as evidence_summary
from aggregated a
where a.sender_count >= 3
  and (
    a.active_blacklisted_sender_count >= 1
    or a.watched_sender_count >= 2
    or a.sender_count >= 5
  );

revoke all on public.operator_sybil_v2_cluster_hub_candidates
