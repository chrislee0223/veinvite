create or replace function public.validate_reward_cohort_funding_adjustment()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_receipt public.vebetter_round_allocations%rowtype;
begin
  select * into v_receipt
  from public.vebetter_round_allocations a
  where a.id = new.allocation_receipt_id;

  if not found
     or v_receipt.network <> new.network
     or v_receipt.app_id <> new.app_id
     or v_receipt.vebetter_round_id + 1 <> new.reward_cohort_round_id then
    raise exception 'REWARD_COHORT_FUNDING_ADJUSTMENT_MISMATCH';
  end if;

  return new;
end;
$$;

