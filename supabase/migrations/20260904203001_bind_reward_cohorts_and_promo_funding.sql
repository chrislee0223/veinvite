  id bigint generated by default as identity primary key,
  network text not null
    check (network in ('mainnet','testnet','testnet-staging')),
  app_id text not null
    check (app_id ~ '^0x[0-9a-f]{64}$'),
  reward_cohort_round_id bigint not null
    check (reward_cohort_round_id >= 1),
  allocation_receipt_id bigint not null
    references public.vebetter_round_allocations(id),
  adjustment_type text not null
    check (adjustment_type in ('PROMOTION')),
  amount_wei numeric(78,0) not null
    check (amount_wei > 0 and amount_wei = trunc(amount_wei)),
  reference_key text not null
    check (length(btrim(reference_key)) between 1 and 120),
  details jsonb not null default '{}'::jsonb
    check (jsonb_typeof(details) = 'object'),
  created_at timestamptz not null default now(),
  constraint reward_cohort_funding_adjustments_uidx
    unique (network, app_id, reward_cohort_round_id, reference_key)
);

