-- Preserve core referral payouts when optional X-promotion split creation is
-- deliberately skipped or cannot complete. A queue row that is exempted here
-- remains a full-reservation referral payout forever; an unrecorded missing
-- LIVE split continues to fail closed.

create table if not exists public.reward_x_promotion_split_exemptions (
  id bigint generated by default as identity primary key,
  queue_entry_id bigint not null references public.reward_queue_entries(id),
  invite_code text not null check (invite_code ~ '^[A-HJ-NP-Z2-9]{7}$'),
  network text not null check (network in ('mainnet','testnet','testnet-staging')),
  recipient_wallet text not null check (recipient_wallet ~ '^0x[0-9a-f]{40}$'),
  reservation_amount_wei numeric(78,0) not null
    check (
      reservation_amount_wei>0
      and reservation_amount_wei=trunc(reservation_amount_wei)
    ),
  exemption_reason text not null check (
    exemption_reason in (
      'FEATURE_DISABLED_AFTER_LIVE_START',
      'LIVE_START_MISSING',
      'POLICY_UNSUPPORTED',
      'DEPENDENCY_GATE_NOT_READY',
      'EXTERNAL_READY_START_MISSING',
      'BEFORE_EXTERNAL_READY_START',
      'EXTERNAL_RUNTIME_NOT_READY',
      'ACTIVE_REFERRAL_LINK_MISSING',
      'SPLIT_CREATION_FAILED'
    )
  ),
  policy_version text not null
    check (char_length(btrim(policy_version)) between 1 and 80),
  details jsonb not null default '{}'::jsonb
    check (jsonb_typeof(details)='object'),
  created_at timestamptz not null default now(),
  constraint reward_x_promotion_split_exemptions_queue_uidx unique(queue_entry_id),
  constraint reward_x_promotion_split_exemptions_invite_uidx unique(invite_code)
);

create index if not exists reward_x_promotion_split_exemptions_network_created_idx
  on public.reward_x_promotion_split_exemptions(network,created_at desc,id desc);

