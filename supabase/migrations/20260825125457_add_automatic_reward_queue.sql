-- Automatically persist verified reward candidates in a durable queue.
-- This migration does not create reward rounds and never transfers B3TR.

begin;

create table if not exists public.reward_queue_entries (
  id bigint generated by default as identity primary key,
  invite_code text not null unique
    references public.invitations(invite_code)
    on update cascade
    on delete restrict,
  recipient_wallet text not null,
  eligibility_check_id bigint not null
    references public.eligibility_check_events(id)
    on delete restrict,
  entry_class text not null,
  eligible_at timestamptz not null,
  status text not null default 'QUEUED',
  assigned_round_id bigint
    references public.reward_rounds(id)
    on delete restrict,
  queued_at timestamptz not null default now(),
  assigned_at timestamptz,
  cancelled_at timestamptz,
  cancel_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint reward_queue_entries_wallet_check
    check (recipient_wallet ~ '^0x[0-9a-f]{40}$'),
  constraint reward_queue_entries_entry_class_check
    check (entry_class in ('NEW','RETURNING')),
  constraint reward_queue_entries_status_check
    check (status in ('QUEUED','ASSIGNED','CANCELLED')),
  constraint reward_queue_entries_shape_check
    check (
      (
        status = 'QUEUED'
        and assigned_round_id is null
        and assigned_at is null
        and cancelled_at is null
        and cancel_reason is null
      )
      or (
        status = 'ASSIGNED'
        and assigned_round_id is not null
        and assigned_at is not null
        and cancelled_at is null
        and cancel_reason is null
      )
      or (
        status = 'CANCELLED'
        and assigned_round_id is null
        and assigned_at is null
        and cancelled_at is not null
        and nullif(btrim(cancel_reason), '') is not null
      )
    )
);

create index if not exists reward_queue_entries_status_eligible_idx
  on public.reward_queue_entries(status, eligible_at, invite_code);
create index if not exists reward_queue_entries_round_idx
  on public.reward_queue_entries(assigned_round_id)
  where assigned_round_id is not null;
create index if not exists reward_queue_entries_recipient_idx
  on public.reward_queue_entries(recipient_wallet);

alter table public.reward_queue_entries enable row level security;
revoke all on table public.reward_queue_entries
  from public, anon, authenticated;
revoke all on sequence public.reward_queue_entries_id_seq
  from public, anon, authenticated;
grant select, insert, update
  on table public.reward_queue_entries
  to service_role;
grant usage, select
  on sequence public.reward_queue_entries_id_seq
  to service_role;
revoke delete, truncate
  on table public.reward_queue_entries
  from service_role;

create or replace function public.set_reward_queue_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

revoke all on function public.set_reward_queue_updated_at()
  from public, anon, authenticated;

drop trigger if exists reward_queue_entries_set_updated_at
  on public.reward_queue_entries;
create trigger reward_queue_entries_set_updated_at
before update on public.reward_queue_entries
for each row execute function public.set_reward_queue_updated_at();

create or replace function public.validate_reward_queue_entry()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_inviter_wallet text;
  v_invitee_wallet text;
  v_activation_network text;
  v_activation_block bigint;
  v_reward_status text;
  v_check_invite_code text;
  v_check_wallet text;
  v_check_network text;
  v_check_block bigint;
  v_check_outcome text;
  v_check_entry_class text;
begin
  select
    inviter_wallet,
    invitee_wallet,
    activation_network,
    activation_block,
    reward_status
  into
    v_inviter_wallet,
    v_invitee_wallet,
    v_activation_network,
    v_activation_block,
    v_reward_status
  from public.invitations
  where invite_code = new.invite_code;

  if not found then
    raise exception 'Reward queue invitation % does not exist', new.invite_code;
  end if;

  if lower(v_inviter_wallet) <> lower(new.recipient_wallet) then
    raise exception 'Reward queue recipient does not match inviter for %', new.invite_code;
  end if;

  select
    invite_code,
    wallet_address,
    network,
    checked_block,
    outcome,
    entry_class
  into
    v_check_invite_code,
    v_check_wallet,
    v_check_network,
    v_check_block,
    v_check_outcome,
    v_check_entry_class
  from public.eligibility_check_events
  where id = new.eligibility_check_id;

  if not found then
    raise exception 'Reward queue eligibility check % does not exist', new.eligibility_check_id;
  end if;

  if v_check_invite_code <> new.invite_code
     or v_invitee_wallet is null
     or lower(v_check_wallet) <> lower(v_invitee_wallet)
     or v_activation_network is null
     or v_check_network <> v_activation_network
     or v_activation_block is null
     or v_check_block > v_activation_block
     or v_check_outcome <> 'ELIGIBLE'
     or v_check_entry_class not in ('NEW','RETURNING')
     or v_check_entry_class <> new.entry_class then
    raise exception 'Reward queue eligibility proof does not match invitation %', new.invite_code;
  end if;

  if new.status = 'QUEUED'
     and v_reward_status <> 'ELIGIBLE' then
    raise exception 'Only reward-eligible invitations can remain queued: %', new.invite_code;
  end if;

  return new;
end;
$$;

revoke all on function public.validate_reward_queue_entry()
  from public, anon, authenticated;

drop trigger if exists reward_queue_entries_validate
  on public.reward_queue_entries;
create trigger reward_queue_entries_validate
before insert or update on public.reward_queue_entries
for each row execute function public.validate_reward_queue_entry();

