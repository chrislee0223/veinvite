create table public.referral_slot_assignments (
    id bigint generated by default as identity primary key,
    relationship_id uuid not null references public.referral_relationships(id) on delete restrict,
    parent_wallet text not null,
    child_wallet text not null,
    slot integer not null,
    assignment_version text not null,
    assigned_at timestamptz not null default now(),
    assigned_by text not null,
    source_snapshot jsonb not null default '{}'::jsonb,
    constraint referral_slot_assignments_slot_check check (slot > 0),
    constraint referral_slot_assignments_parent_wallet_check check (parent_wallet ~ '^0x[0-9a-f]{40}$'),
    constraint referral_slot_assignments_child_wallet_check check (child_wallet ~ '^0x[0-9a-f]{40}$'),
    constraint referral_slot_assignments_different_wallets_check check (parent_wallet <> child_wallet),
    constraint referral_slot_assignments_assignment_version_check check (length(btrim(assignment_version)) > 0),
    constraint referral_slot_assignments_assigned_by_check check (length(btrim(assigned_by)) > 0),
    constraint referral_slot_assignments_source_snapshot_object_check check (jsonb_typeof(source_snapshot) = 'object'),
    constraint referral_slot_assignments_relationship_key unique (relationship_id)
);

create unique index referral_slot_assignments_parent_slot_key
    on public.referral_slot_assignments (lower(parent_wallet), slot);
create index referral_slot_assignments_child_idx
    on public.referral_slot_assignments (lower(child_wallet));

alter table public.referral_slot_assignments enable row level security;
revoke all on table public.referral_slot_assignments from public, anon, authenticated;
revoke all on sequence public.referral_slot_assignments_id_seq from public, anon, authenticated;
grant select, insert on table public.referral_slot_assignments to service_role;
grant usage, select on sequence public.referral_slot_assignments_id_seq to service_role;

create or replace function public.validate_referral_slot_assignment()
returns trigger
language plpgsql
set search_path to 'pg_catalog', 'public'
as $$
declare
    v_parent text;
    v_child text;
begin
    select lower(parent_wallet), lower(child_wallet)
      into v_parent, v_child
    from public.referral_relationships
    where id = new.relationship_id;

    if not found then
        raise exception 'referral relationship % does not exist', new.relationship_id;
    end if;

    if lower(btrim(new.parent_wallet)) <> v_parent
       or lower(btrim(new.child_wallet)) <> v_child then
        raise exception 'slot assignment wallets do not match canonical referral relationship';
    end if;

    new.parent_wallet := v_parent;
    new.child_wallet := v_child;
    return new;
end;
$$;
revoke all on function public.validate_referral_slot_assignment() from public, anon, authenticated, service_role;
create trigger referral_slot_assignments_validate
before insert on public.referral_slot_assignments
for each row execute function public.validate_referral_slot_assignment();

