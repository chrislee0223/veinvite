create table if not exists public.reward_x_promotion_obligations (
  id bigint generated by default as identity primary key,
  split_id bigint not null references public.reward_x_promotion_splits(id),
  invite_code text not null check (invite_code ~ '^[A-HJ-NP-Z2-9]{7}$'),
  network text not null check (network in ('mainnet','testnet','testnet-staging')),
  recipient_wallet text not null check (recipient_wallet ~ '^0x[0-9a-f]{40}$'),
  promotion_amount_wei numeric(78,0) not null
    check (promotion_amount_wei > 0 and promotion_amount_wei=trunc(promotion_amount_wei)),
  source_reward_cohort_round_id bigint not null
    check (source_reward_cohort_round_id >= 1),
  source_allocation_receipt_id bigint not null
    references public.vebetter_round_allocations(id),
  policy_version text not null
    check (char_length(btrim(policy_version)) between 1 and 80),
  financial_state text not null default 'RESERVED'
    check (financial_state in ('RESERVED','HELD','RELEASED','PAID')),
  held_at timestamptz,
  released_at timestamptz,
  paid_at timestamptz,
  release_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reward_x_promotion_obligations_split_uidx unique(split_id),
  constraint reward_x_promotion_obligations_invite_uidx unique(invite_code),
  constraint reward_x_promotion_obligations_state_shape_check check (
    (
      financial_state='RESERVED'
      and held_at is null
      and released_at is null
      and paid_at is null
      and release_reason is null
    )
    or
    (
      financial_state='HELD'
      and held_at is not null
      and released_at is null
      and paid_at is null
      and release_reason is null
    )
    or
    (
      financial_state='RELEASED'
      and released_at is not null
      and paid_at is null
      and release_reason is not null
      and char_length(btrim(release_reason)) between 1 and 120
    )
    or
    (
      financial_state='PAID'
      and held_at is not null
      and released_at is null
      and paid_at is not null
      and release_reason is null
    )
  )
);

