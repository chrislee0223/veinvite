      old.financial_state,
      new.financial_state,
      case
        when new.financial_state='HELD' then 'BASE_PAID_HOLD'
        when new.financial_state='RELEASED' then new.release_reason
        else 'STATE_TRANSITION'
      end,
      current_user
    );
  end if;

  return new;
end;
$function$;

