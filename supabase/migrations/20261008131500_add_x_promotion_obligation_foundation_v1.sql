create or replace function public.validate_reward_x_promotion_obligation_insert()
returns trigger
language plpgsql
set search_path to 'pg_catalog','public'
as $function$
declare
  v_split public.reward_x_promotion_splits%rowtype;
begin
  if new.financial_state<>'RESERVED'
     or new.held_at is not null
     or new.released_at is not null
     or new.paid_at is not null
     or new.release_reason is not null then
    raise exception 'REWARD_X_PROMOTION_OBLIGATION_INITIAL_STATE_INVALID';
  end if;

  select * into v_split
  from public.reward_x_promotion_splits s
  where s.id=new.split_id;

  if not found
     or v_split.mode<>'LIVE'
     or v_split.promotion_amount_wei<=0
     or v_split.invite_code<>new.invite_code
     or v_split.network<>new.network
     or v_split.recipient_wallet<>new.recipient_wallet
     or v_split.promotion_amount_wei<>new.promotion_amount_wei
     or v_split.source_reward_cohort_round_id<>new.source_reward_cohort_round_id
     or v_split.source_allocation_receipt_id<>new.source_allocation_receipt_id
     or btrim(v_split.policy_version)<>btrim(new.policy_version) then
    raise exception 'REWARD_X_PROMOTION_OBLIGATION_SPLIT_MISMATCH';
  end if;

  return new;
end;
$function$;

create or replace function public.guard_reward_x_promotion_obligation_mutation()
returns trigger
language plpgsql
set search_path to 'pg_catalog','public'
as $function$
begin
  if tg_op='DELETE' then
    raise exception 'REWARD_X_PROMOTION_OBLIGATION_DELETE_FORBIDDEN';
  end if;

  if old.split_id is distinct from new.split_id
     or old.invite_code is distinct from new.invite_code
     or old.network is distinct from new.network
     or old.recipient_wallet is distinct from new.recipient_wallet
     or old.promotion_amount_wei is distinct from new.promotion_amount_wei
     or old.source_reward_cohort_round_id is distinct from new.source_reward_cohort_round_id
     or old.source_allocation_receipt_id is distinct from new.source_allocation_receipt_id
     or old.policy_version is distinct from new.policy_version
     or old.created_at is distinct from new.created_at then
    raise exception 'REWARD_X_PROMOTION_OBLIGATION_IDENTITY_IMMUTABLE';
  end if;

  if old.financial_state=new.financial_state then
    raise exception 'REWARD_X_PROMOTION_OBLIGATION_STATE_CHANGE_REQUIRED';
  end if;

  if not (
    (old.financial_state='RESERVED' and new.financial_state in ('HELD','RELEASED'))
    or
    (old.financial_state='HELD' and new.financial_state='RELEASED')
  ) then
    raise exception 'REWARD_X_PROMOTION_OBLIGATION_TRANSITION_INVALID';
  end if;

  return new;
end;
$function$;

