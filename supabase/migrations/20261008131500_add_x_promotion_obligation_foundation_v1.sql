create or replace function public.activate_reward_x_promotion_obligation_v1(
  p_invite_code text
)
returns jsonb
language plpgsql
security definer
set search_path to 'pg_catalog','public'
as $function$
declare
  v_code text := upper(btrim(p_invite_code));
  v_obligation public.reward_x_promotion_obligations%rowtype;
  v_split public.reward_x_promotion_splits%rowtype;
  v_payout public.reward_payouts%rowtype;
  v_invitation public.invitations%rowtype;
  v_now timestamptz := clock_timestamp();
begin
  if v_code is null or v_code !~ '^[A-HJ-NP-Z2-9]{7}$' then
    raise exception 'INVALID_INVITE_CODE';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended('veinvite_x_promotion_' || v_code,0)
  );

  select * into v_obligation
  from public.reward_x_promotion_obligations o
  where o.invite_code=v_code
  for update;

  if not found then
    raise exception 'REWARD_X_PROMOTION_OBLIGATION_MISSING';
  end if;

  if v_obligation.financial_state='HELD' then
    return jsonb_build_object(
      'activated',true,
      'reason','ALREADY_HELD',
      'inviteCode',v_code,
      'amountWei',v_obligation.promotion_amount_wei::text,
      'heldAt',v_obligation.held_at
    );
  end if;

  if v_obligation.financial_state<>'RESERVED' then
    raise exception 'REWARD_X_PROMOTION_OBLIGATION_NOT_RESERVABLE';
  end if;

  select * into v_split
  from public.reward_x_promotion_splits s
  where s.id=v_obligation.split_id
    and s.mode='LIVE';

  if not found then
    raise exception 'REWARD_X_PROMOTION_LIVE_SPLIT_MISSING';
  end if;

  select * into v_payout
  from public.reward_payouts p
  where p.invite_code=v_code
    and p.status='PAID';

  if not found
     or v_payout.amount_wei<>v_split.base_amount_wei
     or v_payout.paid_at is null then
    raise exception 'REWARD_X_PROMOTION_BASE_PAYOUT_MISMATCH';
  end if;

  if not exists (
    select 1
    from public.reward_receipts r
    where r.payout_id=v_payout.id
      and r.invite_code=v_code
      and r.network=v_obligation.network
      and r.recipient_wallet=v_obligation.recipient_wallet
      and r.amount_wei=v_split.base_amount_wei
      and r.paid_at is not null
  ) then
    raise exception 'REWARD_X_PROMOTION_BASE_RECEIPT_MISSING';
  end if;

  select * into v_invitation
  from public.invitations i
  where i.invite_code=v_code;

  if not found
     or public.is_sybil_v2_referral_invalidated(v_code,v_obligation.network)
     or exists (
       select 1
       from public.sybil_v2_wallet_restrictions r
       where r.network=v_obligation.network
         and r.status='ACTIVE'
         and r.wallet_address in (
           lower(v_obligation.recipient_wallet),
           lower(v_invitation.invitee_wallet)
         )
     ) then
    raise exception 'REWARD_X_PROMOTION_SECURITY_NOT_CLEAR';
  end if;

  update public.reward_x_promotion_obligations o
  set financial_state='HELD',
      held_at=v_now,
      updated_at=v_now
  where o.id=v_obligation.id
  returning * into v_obligation;

  return jsonb_build_object(
    'activated',true,
    'reason','HELD',
    'inviteCode',v_code,
    'amountWei',v_obligation.promotion_amount_wei::text,
    'heldAt',v_obligation.held_at
  );
end;
$function$;

create or replace function public.release_reward_x_promotion_obligation_v1(
  p_invite_code text,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path to 'pg_catalog','public'
as $function$
declare
  v_code text := upper(btrim(p_invite_code));
  v_reason text := btrim(coalesce(p_reason,''));
  v_obligation public.reward_x_promotion_obligations%rowtype;
  v_now timestamptz := clock_timestamp();
begin
  if v_code is null or v_code !~ '^[A-HJ-NP-Z2-9]{7}$' then
    raise exception 'INVALID_INVITE_CODE';
  end if;

  if char_length(v_reason) not between 1 and 120 then
    raise exception 'REWARD_X_PROMOTION_RELEASE_REASON_INVALID';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended('veinvite_x_promotion_' || v_code,0)
  );

  select * into v_obligation
  from public.reward_x_promotion_obligations o
  where o.invite_code=v_code
  for update;

  if not found then
    raise exception 'REWARD_X_PROMOTION_OBLIGATION_MISSING';
  end if;

  if v_obligation.financial_state='RELEASED' then
    return jsonb_build_object(
      'released',true,
      'reason','ALREADY_RELEASED',
      'inviteCode',v_code,
      'amountWei',v_obligation.promotion_amount_wei::text,
      'releasedAt',v_obligation.released_at
    );
  end if;

  if v_obligation.financial_state not in ('RESERVED','HELD') then
    raise exception 'REWARD_X_PROMOTION_OBLIGATION_NOT_RELEASABLE';
  end if;

  update public.reward_x_promotion_obligations o
  set financial_state='RELEASED',
      released_at=v_now,
      release_reason=v_reason,
      updated_at=v_now
  where o.id=v_obligation.id
  returning * into v_obligation;

  return jsonb_build_object(
    'released',true,
    'reason',v_reason,
    'inviteCode',v_code,
    'amountWei',v_obligation.promotion_amount_wei::text,
    'releasedAt',v_obligation.released_at
  );
end;
$function$;

create or replace function public.read_reward_x_promotion_post_base_liability_wei(
  p_network text,
  p_app_id text
)
returns numeric
language plpgsql
stable
set search_path to 'pg_catalog','public'
as $function$
declare
  v_veinvite_app_id constant text :=
    '0x29acc8863cf2ab7a82d16c62d61ca84b6650cede4c4fd69073148c875349021e';
  v_network text := lower(btrim(p_network));
  v_app_id text := lower(btrim(p_app_id));
  v_amount numeric(78,0) := 0;
begin
  if v_network not in ('mainnet','testnet','testnet-staging') then
    raise exception 'UNSUPPORTED_NETWORK';
  end if;
  if v_app_id<>v_veinvite_app_id then
    raise exception 'REWARD_X_PROMOTION_APP_MISMATCH';
  end if;

  select coalesce(sum(o.promotion_amount_wei),0)
  into v_amount
  from public.reward_x_promotion_obligations o
  where o.network=v_network
    and o.financial_state='HELD';

  return v_amount;
end;
$function$;

create or replace function public.read_reward_x_promotion_cohort_released_wei(
  p_network text,
  p_app_id text,
  p_reward_cohort_round_id bigint,
  p_allocation_receipt_id bigint
)
returns numeric
language plpgsql
stable
set search_path to 'pg_catalog','public'
as $function$
declare
  v_veinvite_app_id constant text :=
    '0x29acc8863cf2ab7a82d16c62d61ca84b6650cede4c4fd69073148c875349021e';
  v_network text := lower(btrim(p_network));
  v_app_id text := lower(btrim(p_app_id));
  v_receipt public.vebetter_round_allocations%rowtype;
  v_amount numeric(78,0) := 0;
begin
  if v_network not in ('mainnet','testnet','testnet-staging') then
    raise exception 'UNSUPPORTED_NETWORK';
  end if;
  if v_app_id<>v_veinvite_app_id then
    raise exception 'REWARD_X_PROMOTION_APP_MISMATCH';
  end if;

  select * into v_receipt
  from public.vebetter_round_allocations a
  where a.id=p_allocation_receipt_id
    and a.network=v_network
    and a.app_id=v_app_id;

  if not found
     or v_receipt.vebetter_round_id+1<>p_reward_cohort_round_id then
    raise exception 'REWARD_X_PROMOTION_SOURCE_MISMATCH';
  end if;

  select coalesce(sum(o.promotion_amount_wei),0)
  into v_amount
  from public.reward_x_promotion_obligations o
  where o.network=v_network
    and o.source_reward_cohort_round_id=p_reward_cohort_round_id
    and o.source_allocation_receipt_id=p_allocation_receipt_id
    and o.financial_state='RELEASED';

  return v_amount;
end;
$function$;

