create table if not exists public.reward_x_promotion_external_runtime_checks (
  id bigint generated by default as identity primary key,
  network text not null check (network in ('mainnet','testnet','testnet-staging')),
  status text not null check (
    status in (
      'READY',
      'POST_NOT_FOUND',
      'X_API_NOT_CONFIGURED',
      'X_API_AUTH_FAILED',
      'X_API_RATE_LIMITED',
      'X_API_UNAVAILABLE',
      'X_API_RESPONSE_INVALID'
    )
  ),
  probe_post_id text not null check (probe_post_id ~ '^[0-9]{1,32}$'),
  checked_at timestamptz not null default now(),
  details jsonb not null default '{}'::jsonb
    check (jsonb_typeof(details)='object')
);

create index if not exists reward_x_promotion_external_runtime_checks_latest_idx
  on public.reward_x_promotion_external_runtime_checks(network,checked_at desc,id desc);

alter table public.reward_x_promotion_external_runtime_checks enable row level security;

