create table if not exists public.reward_x_promotion_opportunities (
  id bigint generated by default as identity primary key,
  obligation_id bigint not null references public.reward_x_promotion_obligations(id),
  split_id bigint not null references public.reward_x_promotion_splits(id),
  invite_code text not null check (invite_code ~ '^[A-HJ-NP-Z2-9]{7}$'),
  network text not null check (network in ('mainnet','testnet','testnet-staging')),
  recipient_wallet text not null check (recipient_wallet ~ '^0x[0-9a-f]{40}$'),
  promotion_amount_wei numeric(78,0) not null
    check (promotion_amount_wei>0 and promotion_amount_wei=trunc(promotion_amount_wei)),
  policy_version text not null
    check (char_length(btrim(policy_version)) between 1 and 80),
  offer_window_seconds integer not null
    check (offer_window_seconds between 60 and 604800),
  opened_at timestamptz not null,
  post_deadline_at timestamptz not null,
  created_at timestamptz not null default now(),
  constraint reward_x_promotion_opportunities_obligation_uidx unique(obligation_id),
  constraint reward_x_promotion_opportunities_split_uidx unique(split_id),
  constraint reward_x_promotion_opportunities_invite_uidx unique(invite_code),
  constraint reward_x_promotion_opportunities_window_check
    check (
      post_deadline_at =
      opened_at + make_interval(secs => offer_window_seconds)
    )
);

create index if not exists reward_x_promotion_opportunities_network_deadline_idx
  on public.reward_x_promotion_opportunities(network,post_deadline_at,id);

alter table public.reward_x_promotion_opportunities enable row level security;

