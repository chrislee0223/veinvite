create or replace function public.sync_reward_x_promotion_opportunities_v1(
  p_network text,
  p_limit integer default 25
)
returns jsonb
language plpgsql
set search_path to 'pg_catalog','public'
as $function$
declare
  v_network text := lower(btrim(coalesce(p_network,'')));
  v_limit integer := greatest(1,least(coalesce(p_limit,25),100));
  v_candidate record;
  v_activation jsonb;
  v_creation jsonb;
  v_considered integer := 0;
  v_activated integer := 0;
  v_created integer := 0;
  v_already integer := 0;
  v_failed integer := 0;
begin
  if v_network not in ('mainnet','testnet','testnet-staging') then
    raise exception 'UNSUPPORTED_NETWORK';
  end if;

  for v_candidate in
    select
      o.invite_code,
      o.financial_state
    from public.reward_x_promotion_obligations o
    join public.reward_x_promotion_splits s
      on s.id=o.split_id
     and s.mode='LIVE'
    where o.network=v_network
      and o.financial_state in ('RESERVED','HELD')
      and not exists (
        select 1
        from public.reward_x_promotion_opportunities x
        where x.obligation_id=o.id
      )
      and (
        o.financial_state='HELD'
        or exists (
          select 1
          from public.reward_payouts p
          join public.reward_receipts r
            on r.payout_id=p.id
          where p.invite_code=o.invite_code
            and p.recipient_wallet=o.recipient_wallet
            and p.status='PAID'
            and p.amount_wei=s.base_amount_wei
            and p.paid_at is not null
            and r.invite_code=o.invite_code
            and r.network=o.network
            and r.recipient_wallet=o.recipient_wallet
            and r.amount_wei=s.base_amount_wei
            and r.paid_at is not null
        )
      )
    order by o.id
    limit v_limit
  loop
    v_considered:=v_considered+1;

    begin
      if v_candidate.financial_state='RESERVED' then
        v_activation :=
          public.activate_reward_x_promotion_obligation_v1(
            v_candidate.invite_code
          );
        if coalesce((v_activation->>'activated')::boolean,false) then
          v_activated:=v_activated+1;
        end if;
      end if;

      v_creation :=
        public.create_reward_x_promotion_opportunity_v1(
          v_candidate.invite_code
        );

      if coalesce((v_creation->>'created')::boolean,false) then
        v_created:=v_created+1;
      else
        v_already:=v_already+1;
      end if;
    exception when others then
      -- This is intentionally fail-soft and isolated from the core referral
      -- payout. The unchanged RESERVED/HELD row is eligible for a later retry.
      v_failed:=v_failed+1;
    end;
  end loop;

  return jsonb_build_object(
    'network',v_network,
    'consideredCount',v_considered,
    'activatedCount',v_activated,
    'createdCount',v_created,
    'alreadyExistsCount',v_already,
    'failedCount',v_failed
  );
end;
$function$;

revoke all on function public.sync_reward_x_promotion_opportunities_v1(text,integer)
  from public,anon,authenticated;
grant execute on function public.sync_reward_x_promotion_opportunities_v1(text,integer)
  to service_role;

create or replace function public.read_reward_x_promotion_opportunity_audit(
  p_network text
)
returns jsonb
language plpgsql
stable
set search_path to 'pg_catalog','public'
as $function$
declare
  v_network text := lower(btrim(coalesce(p_network,'')));
  v_total integer := 0;
  v_binding_mismatch integer := 0;
  v_window_mismatch integer := 0;
  v_without_held integer := 0;
  v_held_without_opportunity integer := 0;
begin
  if v_network not in ('mainnet','testnet','testnet-staging') then
    raise exception 'UNSUPPORTED_NETWORK';
  end if;

  select
    count(*)::integer,
    count(*) filter (
      where o.id is null
         or s.id is null
         or s.mode<>'LIVE'
         or x.split_id<>s.id
         or x.invite_code<>o.invite_code
         or x.network<>o.network
         or x.recipient_wallet<>o.recipient_wallet
         or x.promotion_amount_wei<>o.promotion_amount_wei
         or x.policy_version<>o.policy_version
    )::integer,
    count(*) filter (
      where x.offer_window_seconds<>86400
         or x.post_deadline_at<>
            x.opened_at+make_interval(secs=>x.offer_window_seconds)
    )::integer,
    count(*) filter (
      where o.financial_state not in ('HELD','RELEASED','PAID')
    )::integer
  into
    v_total,
    v_binding_mismatch,
    v_window_mismatch,
    v_without_held
  from public.reward_x_promotion_opportunities x
  left join public.reward_x_promotion_obligations o
    on o.id=x.obligation_id
  left join public.reward_x_promotion_splits s
    on s.id=x.split_id
  where x.network=v_network;

  select count(*)::integer
  into v_held_without_opportunity
  from public.reward_x_promotion_obligations o
  join public.reward_x_promotion_splits s
    on s.id=o.split_id
   and s.mode='LIVE'
  where o.network=v_network
    and o.financial_state='HELD'
    and not exists (
      select 1
      from public.reward_x_promotion_opportunities x
      where x.obligation_id=o.id
    );

  return jsonb_build_object(
    'ok',
      v_binding_mismatch=0
      and v_window_mismatch=0
      and v_without_held=0
      and v_held_without_opportunity=0,
    'network',v_network,
    'totalCount',v_total,
    'violations',jsonb_build_object(
      'binding',v_binding_mismatch,
      'window',v_window_mismatch,
      'opportunityWithoutHeldHistory',v_without_held,
      'heldWithoutOpportunity',v_held_without_opportunity
    )
  );
end;
$function$;

revoke all on function public.read_reward_x_promotion_opportunity_audit(text)
