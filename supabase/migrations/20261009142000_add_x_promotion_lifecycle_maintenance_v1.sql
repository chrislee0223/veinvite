create or replace function public.record_reward_x_promotion_verification_attempt_v1(
  p_invite_code text,
  p_submission_id bigint,
  p_verification_id bigint,
  p_phase text,
  p_x_post_id text,
  p_outcome text,
  p_reason text,
  p_details jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path to 'pg_catalog','public'
as $function$
declare
  v_code text := upper(btrim(coalesce(p_invite_code,'')));
  v_phase text := upper(btrim(coalesce(p_phase,'')));
  v_post_id text := btrim(coalesce(p_x_post_id,''));
  v_outcome text := upper(btrim(coalesce(p_outcome,'')));
  v_reason text := upper(btrim(coalesce(p_reason,'')));
  v_submission public.reward_x_promotion_post_submissions%rowtype;
  v_verification public.reward_x_promotion_post_verifications%rowtype;
  v_created public.reward_x_promotion_verification_attempts%rowtype;
begin
  if v_code !~ '^[A-HJ-NP-Z2-9]{7}$' then
    raise exception 'INVALID_INVITE_CODE';
  end if;
  if v_phase not in ('INITIAL_RETRY','FINAL_CHECK') then
    raise exception 'REWARD_X_PROMOTION_ATTEMPT_PHASE_INVALID';
  end if;
  if v_outcome not in (
    'RETRY','INITIAL_VERIFIED','INVALIDATED','REVIEW_REQUIRED','FINAL_VERIFIED'
  ) then
    raise exception 'REWARD_X_PROMOTION_ATTEMPT_OUTCOME_INVALID';
  end if;
  if v_post_id !~ '^[0-9]{1,32}$' then
    raise exception 'REWARD_X_PROMOTION_POST_ID_INVALID';
  end if;
  if char_length(v_reason) not between 1 and 120 then
    raise exception 'REWARD_X_PROMOTION_ATTEMPT_REASON_INVALID';
  end if;
  if p_details is null or jsonb_typeof(p_details)<>'object' then
    raise exception 'REWARD_X_PROMOTION_ATTEMPT_DETAILS_INVALID';
  end if;

  select * into v_submission
  from public.reward_x_promotion_post_submissions s
  where s.id=p_submission_id
    and s.invite_code=v_code
    and s.x_post_id=v_post_id;

  if not found then
    raise exception 'REWARD_X_PROMOTION_ATTEMPT_SUBMISSION_MISSING';
  end if;

  if v_phase='INITIAL_RETRY' then
    if p_verification_id is not null then
      raise exception 'REWARD_X_PROMOTION_ATTEMPT_PHASE_MISMATCH';
    end if;
  else
    if p_verification_id is null then
      raise exception 'REWARD_X_PROMOTION_ATTEMPT_VERIFICATION_REQUIRED';
    end if;

    select * into v_verification
    from public.reward_x_promotion_post_verifications p
    where p.id=p_verification_id
      and p.submission_id=v_submission.id
      and p.invite_code=v_code
      and p.x_post_id=v_post_id;

    if not found then
      raise exception 'REWARD_X_PROMOTION_ATTEMPT_VERIFICATION_MISSING';
    end if;
  end if;

  insert into public.reward_x_promotion_verification_attempts(
    network,invite_code,submission_id,verification_id,
    phase,x_post_id,outcome,reason,details
  ) values (
    v_submission.network,v_code,v_submission.id,p_verification_id,
    v_phase,v_post_id,v_outcome,v_reason,p_details
  )
  returning * into v_created;

  return jsonb_build_object(
    'recorded',true,
    'attemptId',v_created.id,
    'inviteCode',v_code,
    'phase',v_created.phase,
    'outcome',v_created.outcome,
    'attemptedAt',v_created.attempted_at
  );
end;
$function$;

create or replace function public.read_reward_x_promotion_pending_post_candidates_v1(
  p_network text,
  p_limit integer default 10
)
returns jsonb
language plpgsql
stable security definer
set search_path to 'pg_catalog','public'
as $function$
declare
  v_network text := lower(btrim(coalesce(p_network,'')));
  v_limit integer := greatest(1,least(coalesce(p_limit,10),50));
  v_rows jsonb;
begin
  if v_network not in ('mainnet','testnet','testnet-staging') then
    raise exception 'UNSUPPORTED_NETWORK';
  end if;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'inviteCode',c.invite_code,
        'submissionId',c.submission_id,
        'xPostId',c.x_post_id,
        'shareToken',c.share_token,
        'submittedAt',c.submitted_at
      )
      order by c.submitted_at,c.submission_id
    ),
    '[]'::jsonb
  )
  into v_rows
  from (
    select
      u.invite_code,
      u.id as submission_id,
      u.x_post_id,
      x.share_token::text as share_token,
      u.submitted_at
    from public.reward_x_promotion_post_submissions u
    join public.reward_x_promotion_opportunities x
      on x.id=u.opportunity_id
    join public.reward_x_promotion_obligations o
      on o.id=u.obligation_id
    left join lateral (
      select max(a.attempted_at) as latest_attempt_at
      from public.reward_x_promotion_verification_attempts a
      where a.submission_id=u.id
        and a.phase='INITIAL_RETRY'
    ) retry on true
    where u.network=v_network
      and u.submission_state='PENDING'
      and o.financial_state='HELD'
      and u.submitted_at <= now()-interval '10 minutes'
      and (
        retry.latest_attempt_at is null
        or retry.latest_attempt_at <= now()-interval '15 minutes'
      )
    order by
      coalesce(retry.latest_attempt_at,u.submitted_at),
      u.id
    limit v_limit
  ) c;

  return jsonb_build_object(
    'network',v_network,
    'candidateCount',jsonb_array_length(v_rows),
    'candidates',v_rows
  );
end;
$function$;

