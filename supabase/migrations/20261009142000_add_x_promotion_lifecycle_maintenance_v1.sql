create or replace function public.mark_reward_x_promotion_post_review_required_v1(
  p_invite_code text,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path to 'pg_catalog','public'
as $function$
declare
  v_code text := upper(btrim(coalesce(p_invite_code,'')));
  v_reason text := upper(btrim(coalesce(p_reason,'')));
  v_verification public.reward_x_promotion_post_verifications%rowtype;
  v_now timestamptz := clock_timestamp();
begin
  if v_code !~ '^[A-HJ-NP-Z2-9]{7}$' then
    raise exception 'INVALID_INVITE_CODE';
  end if;
  if char_length(v_reason) not between 1 and 120 then
    raise exception 'REWARD_X_PROMOTION_REVIEW_REASON_INVALID';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended('veinvite_x_promotion_' || v_code,0)
  );

  select * into v_verification
  from public.reward_x_promotion_post_verifications p
  where p.invite_code=v_code
  for update;

  if not found then
    raise exception 'REWARD_X_PROMOTION_POST_VERIFICATION_MISSING';
  end if;

  if v_verification.verification_state='REVIEW_REQUIRED' then
    return jsonb_build_object(
      'updated',false,
      'reason','ALREADY_REVIEW_REQUIRED',
      'inviteCode',v_code,
      'verificationId',v_verification.id,
      'state',v_verification.verification_state
    );
  end if;

  if v_verification.verification_state not in ('INITIAL_VERIFIED') then
    return jsonb_build_object(
      'updated',false,
      'reason','TERMINAL_STATE',
      'inviteCode',v_code,
      'verificationId',v_verification.id,
      'state',v_verification.verification_state
    );
  end if;

  update public.reward_x_promotion_post_verifications p
  set verification_state='REVIEW_REQUIRED',
      state_reason=v_reason,
      final_verified_at=null,
      invalidated_at=null,
      updated_at=v_now
  where p.id=v_verification.id
  returning * into v_verification;

  return jsonb_build_object(
    'updated',true,
    'reason',v_reason,
    'inviteCode',v_code,
    'verificationId',v_verification.id,
    'state',v_verification.verification_state
  );
end;
$function$;

create or replace function public.invalidate_reward_x_promotion_post_verification_v1(
  p_invite_code text,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path to 'pg_catalog','public'
as $function$
declare
  v_code text := upper(btrim(coalesce(p_invite_code,'')));
  v_reason text := upper(btrim(coalesce(p_reason,'')));
  v_verification public.reward_x_promotion_post_verifications%rowtype;
  v_obligation public.reward_x_promotion_obligations%rowtype;
  v_now timestamptz := clock_timestamp();
begin
  if v_code !~ '^[A-HJ-NP-Z2-9]{7}$' then
    raise exception 'INVALID_INVITE_CODE';
  end if;
  if v_reason not in (
    'POST_NOT_FOUND',
    'SHARE_TOKEN_MISSING',
    'POST_NOT_ORIGINAL',
    'POST_IDENTITY_MISMATCH',
    'POST_AUTHOR_MISMATCH'
  ) then
    raise exception 'REWARD_X_PROMOTION_VERIFICATION_INVALID_REASON';
  end if;

  perform pg_advisory_xact_lock(
    hashtextextended('veinvite_x_promotion_' || v_code,0)
  );

  select * into v_verification
  from public.reward_x_promotion_post_verifications p
  where p.invite_code=v_code
  for update;

  if not found then
    raise exception 'REWARD_X_PROMOTION_POST_VERIFICATION_MISSING';
  end if;

  if v_verification.verification_state='FINAL_VERIFIED' then
    raise exception 'REWARD_X_PROMOTION_FINAL_VERIFICATION_IMMUTABLE';
  end if;

  if v_verification.verification_state<>'INVALID' then
    update public.reward_x_promotion_post_verifications p
    set verification_state='INVALID',
        final_verified_at=null,
        invalidated_at=v_now,
        state_reason=v_reason,
        updated_at=v_now
    where p.id=v_verification.id
    returning * into v_verification;
  end if;

  select * into v_obligation
  from public.reward_x_promotion_obligations o
  where o.id=v_verification.obligation_id
  for update;

  if not found then
    raise exception 'REWARD_X_PROMOTION_OBLIGATION_MISSING';
  end if;

  if v_obligation.financial_state='HELD' then
    update public.reward_x_promotion_obligations o
    set financial_state='RELEASED',
        released_at=v_now,
        release_reason='FINAL_' || v_reason,
        updated_at=v_now
    where o.id=v_obligation.id
    returning * into v_obligation;
  elsif v_obligation.financial_state<>'RELEASED' then
    raise exception 'REWARD_X_PROMOTION_OBLIGATION_NOT_RELEASABLE';
  end if;

  return jsonb_build_object(
    'invalidated',true,
    'reason',v_reason,
    'inviteCode',v_code,
    'verificationId',v_verification.id,
    'verificationState',v_verification.verification_state,
    'financialState',v_obligation.financial_state,
    'releasedAt',v_obligation.released_at
  );
end;
$function$;

create or replace function public.expire_reward_x_promotion_opportunities_v1(
  p_network text,
  p_limit integer default 25
)
returns jsonb
language plpgsql
set search_path to 'pg_catalog','public'
as $function$
declare
  v_network text := lower(btrim(coalesce(p_network,'')));
  v_limit integer := greatest(1,least(coalesce(p_limit,25),100));
  v_candidate record;
  v_opportunity public.reward_x_promotion_opportunities%rowtype;
  v_obligation public.reward_x_promotion_obligations%rowtype;
  v_now timestamptz;
  v_considered integer := 0;
  v_released integer := 0;
  v_skipped integer := 0;
begin
  if v_network not in ('mainnet','testnet','testnet-staging') then
    raise exception 'UNSUPPORTED_NETWORK';
  end if;

  for v_candidate in
    select x.invite_code
    from public.reward_x_promotion_opportunities x
    join public.reward_x_promotion_obligations o
      on o.id=x.obligation_id
    where x.network=v_network
      and o.financial_state='HELD'
      and now() >
        x.post_deadline_at +
        make_interval(secs=>x.submission_grace_seconds)
    order by x.post_deadline_at,x.id
    limit v_limit
  loop
    v_considered:=v_considered+1;

    perform pg_advisory_xact_lock(
      hashtextextended('veinvite_x_promotion_' || v_candidate.invite_code,0)
    );

    v_now:=clock_timestamp();

    select * into v_opportunity
    from public.reward_x_promotion_opportunities x
    where x.invite_code=v_candidate.invite_code;

    select * into v_obligation
    from public.reward_x_promotion_obligations o
    where o.invite_code=v_candidate.invite_code
    for update;

    if not found
       or v_obligation.financial_state<>'HELD'
       or v_now <=
          v_opportunity.post_deadline_at +
          make_interval(secs=>v_opportunity.submission_grace_seconds)
       or exists (
         select 1
         from public.reward_x_promotion_post_submissions s
         where s.opportunity_id=v_opportunity.id
           and s.submission_state in ('PENDING','VERIFIED')
       )
       or exists (
         select 1
         from public.reward_x_promotion_post_verifications p
         where p.opportunity_id=v_opportunity.id
           and p.verification_state in (
             'INITIAL_VERIFIED','REVIEW_REQUIRED','FINAL_VERIFIED'
           )
       ) then
      v_skipped:=v_skipped+1;
      continue;
    end if;

    update public.reward_x_promotion_obligations o
    set financial_state='RELEASED',
        released_at=v_now,
        release_reason='NO_VALID_POST_BEFORE_DEADLINE',
        updated_at=v_now
    where o.id=v_obligation.id;

    v_released:=v_released+1;
  end loop;

  return jsonb_build_object(
    'network',v_network,
    'consideredCount',v_considered,
    'releasedCount',v_released,
    'skippedCount',v_skipped
  );
end;
$function$;

create or replace function public.release_terminal_reward_x_promotion_security_v1(
  p_network text,
  p_limit integer default 25
)
returns jsonb
language plpgsql
set search_path to 'pg_catalog','public'
as $function$
declare
  v_network text := lower(btrim(coalesce(p_network,'')));
  v_limit integer := greatest(1,least(coalesce(p_limit,25),100));
  v_candidate record;
  v_obligation public.reward_x_promotion_obligations%rowtype;
  v_invitation public.invitations%rowtype;
  v_terminal boolean;
  v_invitation_found boolean;
  v_now timestamptz;
  v_considered integer := 0;
  v_released integer := 0;
begin
  if v_network not in ('mainnet','testnet','testnet-staging') then
    raise exception 'UNSUPPORTED_NETWORK';
  end if;

  for v_candidate in
    select o.invite_code
    from public.reward_x_promotion_obligations o
    join public.invitations i
      on i.invite_code=o.invite_code
    where o.network=v_network
      and o.financial_state in ('RESERVED','HELD')
      and (
        public.is_sybil_v2_referral_invalidated(
          o.invite_code,
          v_network
        )
        or exists (
          select 1
          from public.sybil_v2_wallet_restrictions r
          where r.network=v_network
            and r.status='ACTIVE'
            and r.wallet_address in (
              lower(o.recipient_wallet),
              lower(i.invitee_wallet)
            )
        )
      )
    order by o.id
    limit v_limit
  loop
    v_considered:=v_considered+1;

    perform pg_advisory_xact_lock(
      hashtextextended('veinvite_x_promotion_' || v_candidate.invite_code,0)
    );

    select * into v_obligation
    from public.reward_x_promotion_obligations o
    where o.invite_code=v_candidate.invite_code
    for update;

    if not found
       or v_obligation.financial_state not in ('RESERVED','HELD') then
      continue;
    end if;

    select * into v_invitation
    from public.invitations i
    where i.invite_code=v_candidate.invite_code;
    v_invitation_found:=found;

    v_terminal :=
      public.is_sybil_v2_referral_invalidated(
        v_candidate.invite_code,
        v_network
      )
      or (
        v_invitation_found and exists (
          select 1
          from public.sybil_v2_wallet_restrictions r
          where r.network=v_network
            and r.status='ACTIVE'
            and r.wallet_address in (
              lower(v_obligation.recipient_wallet),
              lower(v_invitation.invitee_wallet)
            )
        )
      );

    if not v_terminal then
      continue;
    end if;

    v_now:=clock_timestamp();

    update public.reward_x_promotion_post_submissions s
    set submission_state='INVALID',
        verified_at=null,
        invalidated_at=v_now,
        state_reason='SECURITY_TERMINAL',
        updated_at=v_now
    where s.invite_code=v_candidate.invite_code
      and s.submission_state='PENDING';

    update public.reward_x_promotion_post_verifications p
    set verification_state='INVALID',
        final_verified_at=null,
        invalidated_at=v_now,
        state_reason='SECURITY_TERMINAL',
        updated_at=v_now
    where p.invite_code=v_candidate.invite_code
      and p.verification_state in ('INITIAL_VERIFIED','REVIEW_REQUIRED');

    update public.reward_x_promotion_obligations o
    set financial_state='RELEASED',
        released_at=v_now,
        release_reason='SYBIL_TERMINAL',
        updated_at=v_now
    where o.id=v_obligation.id;

    v_released:=v_released+1;
  end loop;

  return jsonb_build_object(
    'network',v_network,
    'consideredCount',v_considered,
    'releasedCount',v_released
  );
end;
