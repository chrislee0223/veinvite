create table if not exists public.reward_x_promotion_verification_attempts (
  id bigint generated by default as identity primary key,
  network text not null check (network in ('mainnet','testnet','testnet-staging')),
  invite_code text not null check (invite_code ~ '^[A-HJ-NP-Z2-9]{7}$'),
  submission_id bigint not null
    references public.reward_x_promotion_post_submissions(id),
  verification_id bigint
    references public.reward_x_promotion_post_verifications(id),
  phase text not null
    check (phase in ('INITIAL_RETRY','FINAL_CHECK')),
  x_post_id text not null
    check (x_post_id ~ '^[0-9]{1,32}$'),
  outcome text not null
    check (outcome in (
      'RETRY',
      'INITIAL_VERIFIED',
      'INVALIDATED',
      'REVIEW_REQUIRED',
      'FINAL_VERIFIED'
    )),
  reason text not null
    check (char_length(btrim(reason)) between 1 and 120),
  details jsonb not null default '{}'::jsonb
    check (jsonb_typeof(details)='object'),
  attempted_at timestamptz not null default now(),
  constraint reward_x_promotion_attempt_phase_shape_check check (
    (phase='INITIAL_RETRY' and verification_id is null)
    or
    (phase='FINAL_CHECK' and verification_id is not null)
  )
);

create index if not exists reward_x_promotion_attempt_submission_idx
  on public.reward_x_promotion_verification_attempts(
    submission_id,phase,attempted_at desc,id desc
  );

create index if not exists reward_x_promotion_attempt_verification_idx
  on public.reward_x_promotion_verification_attempts(
    verification_id,attempted_at desc,id desc
  )
  where verification_id is not null;

create or replace function public.validate_reward_x_promotion_verification_attempt_insert()
returns trigger
language plpgsql
set search_path to 'pg_catalog','public'
as $function$
declare
  v_submission public.reward_x_promotion_post_submissions%rowtype;
  v_verification public.reward_x_promotion_post_verifications%rowtype;
begin
  select * into v_submission
  from public.reward_x_promotion_post_submissions s
  where s.id=new.submission_id;

  if not found
     or v_submission.invite_code<>new.invite_code
     or v_submission.network<>new.network
     or v_submission.x_post_id<>new.x_post_id then
    raise exception 'REWARD_X_PROMOTION_ATTEMPT_SUBMISSION_MISMATCH';
  end if;

  if new.phase='INITIAL_RETRY' then
    if new.verification_id is not null then
      raise exception 'REWARD_X_PROMOTION_ATTEMPT_PHASE_MISMATCH';
    end if;
  else
    select * into v_verification
    from public.reward_x_promotion_post_verifications p
    where p.id=new.verification_id;

    if not found
       or v_verification.submission_id<>new.submission_id
       or v_verification.invite_code<>new.invite_code
       or v_verification.network<>new.network
       or v_verification.x_post_id<>new.x_post_id then
      raise exception 'REWARD_X_PROMOTION_ATTEMPT_VERIFICATION_MISMATCH';
    end if;
  end if;

  return new;
end;
$function$;

